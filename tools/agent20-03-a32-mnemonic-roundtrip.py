#!/usr/bin/env python3
"""Independent LLVM mnemonic A32 assembly of original reference (verification only).

Not part of the typed source generator. This reads public A32 mnemonic syntax,
checks explicit data pools, assembles via Clang and compares against typed Rust.
"""
from pathlib import Path
import argparse,re,subprocess,struct
p=argparse.ArgumentParser();p.add_argument('--disasm',type=Path,required=True);p.add_argument('--start',type=lambda x:int(x,0),required=True);p.add_argument('--end',type=lambda x:int(x,0),required=True);p.add_argument('--data',action='append',type=str,default=[]);p.add_argument('--reference',type=Path,required=True);p.add_argument('--generated',type=Path,required=True);p.add_argument('--workdir',type=Path,required=True)
a=p.parse_args()
ranges=[tuple(map(lambda x:int(x,0),q.split(':'))) for q in a.data]
for left,right in ranges:
 assert a.start<=left<right<=a.end and (left|right)&3==0
assert not any(ranges[i-1][1]>ranges[i][0] for i in range(1,len(ranges)))
ref=a.reference.read_bytes();headers=[];inst={};targets=set()
pattern=re.compile(r'^\s*([0-9a-f]+):\s+[0-9a-f]{8}\s+([a-z0-9.<>]+)(?:\s+(.*))?$')
for line in a.disasm.read_text().splitlines():
 m=pattern.match(line)
 if not m:continue
 v=int(m[1],16)
 if a.start<=v<a.end:
  if any(l<=v<r for l,r in ranges):continue
  instr=m[2]+' '+re.split(r'\s+@\s+',re.sub(r'\s+<[^>]+>','',m[3] or ''))[0]
  name=instr.split()[0]
  if name in {'b','bl','blx'} or (name.startswith('b') and name[1:] in {'eq','ne','cs','cc','mi','pl','hi','ls','ge','lt','gt','le','lo','hs'}):
   arg=instr.split()[1] if len(instr.split())>1 else ''
   if re.fullmatch(r'0x[0-9a-f]+',arg):
    t=int(arg,16)
    targets.add(t)
    instr=f'{name} TARGET_{t:08x}'
  inst[v]=instr
asm=['.syntax unified','.arm','.text']
for t in sorted(t for t in targets if t<a.start):
 asm.extend([f'.org 0x{t:x}',f'TARGET_{t:08x}:'])
asm.extend([f'.org 0x{a.start:x}','.global entry','entry:'])
compiled_code=compiled_data=0
for v in range(a.start,a.end,4):
 if v in targets:asm.append(f'TARGET_{v:08x}:')
 isdata=any(l<=v<r for l,r in ranges)
 if isdata:
  word=struct.unpack_from('<I',ref,v+0x4000)[0]
  asm.append(f'  .word 0x{word:08x}  @ literal/reference-only data, {v:#x}')
  compiled_data+=4
 else:
  if v not in inst:raise ValueError(f'missing mnemonic at {v:#x}')
  asm.append('  '+inst[v])
  compiled_code+=4
for t in sorted(t for t in targets if t>=a.end):
 asm.extend([f'.org 0x{t:x}',f'TARGET_{t:08x}:'])
b=a.workdir;a.workdir.mkdir(exist_ok=True,parents=True);src=b/'independent.S';obj=b/'independent.o';binary=b/'independent.bin';src.write_text('\n'.join(asm)+'\n')
subprocess.run(['clang','--target=armv7a-none-eabi','-c',str(src),'-o',str(obj)],check=True)
linked=b/'independent.elf'
subprocess.run(['ld.lld','-flavor','gnu','-m','armelf_linux_eabi','-Ttext=0','-e','entry',str(obj),'-o',str(linked)],check=True)
subprocess.run(['llvm-objcopy','--only-section=.text','-O','binary',str(linked),str(binary)],check=True)
out=binary.read_bytes()[a.start:a.end];exp=a.generated.read_bytes();start=a.start;end=a.end
if len(exp)==a.end-a.start:fragment=exp
elif len(exp)>a.end-a.start:fragment=exp[-(a.end-a.start):]
else:raise ValueError('generated bytes too short')
assert out==fragment, ('assembled mnemonic mismatch',next(((a.start+i,out[i],fragment[i]) for i in range(len(out)) if out[i]!=fragment[i]),None))
assert out==ref[a.start+0x4000:a.end+0x4000]
print('Independent mnemonic reassembly matches',len(out),'bytes (',compiled_code//4,'instructions;',compiled_data//4,'data words )')

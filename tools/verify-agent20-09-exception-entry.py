"""Verify Hexagon V66 thread-local exception entry, typed fields and packet layout.

HTID/S54 reads remain Rizin-corroborated because LLVM6 does not accept the
privileged system register names; 13 scalar/extended LLVM6 checks do apply.
"""
import argparse,importlib.util,re,subprocess,tempfile
from pathlib import Path

START=0x471c
PHYSICAL=0x96c0_171c
SIZE=0x44
EXPECTED={
    0x471c:'r23=htid',
    0x4720:'r23=asl(r23,#0x2)',
    0x4724:'r23=asl(r23,#0x12)',
    0x4728:'r23.l=#0x58a0',
    0x472c:'r23|=lsr(r23,#0x10)',
    0x4730:'r23.h=#0xfe02',
    0x4734:'r22=s54',
    0x4738:'r23=add(r23,r22)',
    0x473c:'immext(##0xfe025400)',
    0x4740:'r23=add(r22,##-0x1fdabe0)',
    0x4744:'memd(r23+##0x0)=r1:0',
    0x4748:'r22=htid',
    0x474c:'r1=add(r23,##0x68)',
    0x4750:'r1+=mpyi(r22,##0xe0)',
    0x4754:'jump0x96c01758',
    0x4758:'r1=sp',
    0x475c:'sp=r1',
}
ASM='''.text
.global samples
samples:
{ r23 = asl(r23,#2) }
{ r23 = asl(r23,#18) }
{ r23.l = #0x58a0 }
{ r23 |= lsr(r23,#16) }
{ r23.h = #0xfe02 }
{ r23 = add(r23,r22) }
{ r23 = add(r22,##-0x1fdabe0) }
{ memd(r23+#0) = r1:0 }
{ r1 = add(r23,#104) }
{ r1 += mpyi(r22,#224) }
{ jump target }
{ r1 = sp
  sp = r1 }
target:
{ nop }
'''

def extract_elf(path:Path)->bytes:
    f=Path(__file__).with_name('verify-cdsp-hexagon-entry.py')
    spec=importlib.util.spec_from_file_location('agent20_exception_entry',f)
    assert spec and spec.loader
    obj=importlib.util.module_from_spec(spec);spec.loader.exec_module(obj)
    return obj.parse_elf32_text(path.read_bytes())

def verify(llvm:Path,rz:Path,emitted:Path,reference:Path):
    b=emitted.read_bytes()
    if len(b)!=SIZE:raise ValueError(f'wrong exception-entry size {len(b)}')
    if reference.read_bytes()[START:START+SIZE]!=b:
        raise ValueError('source-generated exception-entry differs from CDSP reference')
    p=subprocess.run([str(rz),'-a','hexagon','-b','32','-o',hex(PHYSICAL),'-D',b.hex()],capture_output=True,text=True,check=True)
    rows={}
    for line in p.stdout.splitlines():
        m=re.match(r'^0x([a-fA-F0-9]+)\s+4\s+[a-fA-F0-9]{8}\s+[?\\/\[|]\s+(.*)',line)
        if m:rows[int(m[1],16)]=''.join(m[2].lower().split())
    if len(rows)!=SIZE//4:raise ValueError(f'Rizin decoded {len(rows)} instead of {SIZE//4} words')
    for offset,expected in EXPECTED.items():
        got=rows.get(PHYSICAL+(offset-START),'')
        if expected not in got:raise ValueError(f'V66 decode unexpected at {offset:#x}: {got!r} expected {expected!r}')
    with tempfile.TemporaryDirectory(prefix='cdsp-exception-llvm-') as d:
        s=Path(d)/'sample.s';o=Path(d)/'sample.o';s.write_text(ASM)
        subprocess.run([str(llvm),'-triple=hexagon','-mcpu=hexagonv60','-filetype=obj','-o',str(o),str(s)],capture_output=True,text=True,check=True)
        built=extract_elf(o)
    checked=[(0x4720,0),(0x4724,4),(0x4728,8),(0x472c,12),(0x4730,16),(0x4738,20),
             (0x473c,24),(0x4740,28),(0x4744,32),(0x474c,36),(0x4750,40),(0x4758,48),(0x475c,52)]
    for a,offset in checked:
        got=int.from_bytes(b[a-START:a-START+4],'little')
        independent=int.from_bytes(built[offset:offset+4],'little')
        if got & ~0xc000 != independent & ~0xc000:
            raise ValueError(f'LLVM6 scalar/extended encoding mismatch at {a:#x}')
    # LLVM6 jump to a synthetic local label is not the same displacement as
    # the original packet-relative branch; its instruction family is checked.
    direct=int.from_bytes(b[0x4754-START:0x4758-START],'little')
    llvm_jump=int.from_bytes(built[44:48],'little')
    if direct&0xfc00_0000 != llvm_jump&0xfc00_0000:
        raise ValueError('jump opcode family differs from independently assembled LLVM6 form')
    print('Hexagon exception-entry: 68/68 generated bytes exact, 17 Rizin V66 decoded words and 13 LLVM6 instruction-field matches; HTID/S54 only decoder-correlated.')

def main():
    ap=argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--llvm-mc',type=Path,required=True)
    ap.add_argument('--rz-asm',type=Path,required=True)
    ap.add_argument('--rust-output',type=Path,required=True)
    ap.add_argument('--reference',type=Path,required=True)
    args=ap.parse_args();verify(args.llvm_mc,args.rz_asm,args.rust_output,args.reference)
if __name__=='__main__':main()

"""Rebuild ADSP controller clock / thread-start hook [0x13850,0x138ec).

Source-assemble ordinary Hexagon V66 packets with LLVM6. Five privileged
system reads, start and lock/unlock instructions are generated by checked ISA
constructors. Two parse markers preserve the controller scheduler grouping.
"""
from __future__ import annotations
import argparse,hashlib,importlib.util,struct,sys
from pathlib import Path
T=Path(__file__).resolve().parent
if str(T) not in sys.path:sys.path.insert(0,str(T))
from adsp_hexagon_v66 import (KernelZeroLock,packet_continuation,
    read_system_register_pair,start_thread_from_register)
START=0x13850;END=0x138ec;SIZE=END-START;PHYSICAL=0x8be10850
SOURCE=T/'adsp-agent20-rwe-next-controller-runtime-clock.S'
REFERENCE_SHA='4b579e5dc1333d634e5bdc93f3314e357e0e30dab7140833f6cc7aef086b1c1e'
NOP=struct.pack('<I',0x7f00c000)
SPECIAL={0x13864:read_system_register_pair(0,30),
         0x138ac:start_thread_from_register(0),
         0x138b0:int(KernelZeroLock.LOCK),
         0x138bc:int(KernelZeroLock.UNLOCK),
         0x138c0:read_system_register_pair(2,30)}
PACKET_CONTINUATIONS=(0x1386c,0x13878)

def render(llvm_mc:str)->bytes:
 sp=importlib.util.spec_from_file_location('emitter',T/'emit-adsp-entry.py')
 if not sp or not sp.loader:raise RuntimeError('Missing LLVM6 emitter')
 em=importlib.util.module_from_spec(sp);sp.loader.exec_module(em)
 data=bytearray(em.assemble(llvm_mc,SOURCE,SIZE))
 for addr,opcode in SPECIAL.items():
  at=addr-START
  if data[at:at+4]!=NOP:raise em.AdspError(f'Expected checked V66 slot at 0x{addr:x}')
  struct.pack_into('<I',data,at,opcode)
 for addr in PACKET_CONTINUATIONS:
  at=addr-START;word=struct.unpack_from('<I',data,at)[0]
  adjusted=packet_continuation(word)
  if word & ~0xc000!=adjusted & ~0xc000:
   raise em.AdspError('Packet parse update changed operand bits')
  struct.pack_into('<I',data,at,adjusted)
 if any(data[i:i+4]==NOP for i in range(0,SIZE,4)):
  raise em.AdspError('Unresolved V66 source slot')
 return bytes(data)

def verify(ref:bytes,built:bytes)->None:
 if hashlib.sha256(ref).hexdigest()!=REFERENCE_SHA:
  raise ValueError('Wrong pinned ADSP firmware revision')
 if len(built)!=SIZE or built!=ref[START:END]:
  raise ValueError('ADSP runtime clock wrapper differs from reference')
 if ref[START-12:START]!=bytes(12) or ref[END:END+4]!=bytes(4):
  raise ValueError('Expected precise linker fill around runtime clock')

def main()->int:
 p=argparse.ArgumentParser(description=__doc__)
 p.add_argument('--llvm-mc',required=True);p.add_argument('--reference',type=Path)
 p.add_argument('--output',type=Path,required=True)
 a=p.parse_args();b=render(a.llvm_mc)
 if a.reference:verify(a.reference.read_bytes(),b)
 a.output.write_bytes(b)
 print(f'ADSP runtime clock: {SIZE} exact executable bytes file [0x{START:x},0x{END:x}), '
       f'physical [0x{PHYSICAL:x},0x{PHYSICAL+SIZE:x}); 34 LLVM6 instructions, '
       f'five typed V66 words, two checked parse markers; SHA-256={hashlib.sha256(b).hexdigest()}')
 return 0
if __name__=='__main__':raise SystemExit(main())

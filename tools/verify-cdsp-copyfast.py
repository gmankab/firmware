"""Verify a source-generated CDSP Hexagon V66 fast-cache-copy function.

LLVM6 independently reassembles the entire body (76 bytes). The only two
byte differences are the Hexagon `endloop01` parse marker bits: LLVM6 lacks
that bundle option, and the emitter preserves those markers explicitly.
The LLVM fixture's 24-byte prefix is shorter than the 32-byte V66 original
because LLVM6 chooses a non-extended GP-relative load and compresses the
constant 128. Rizin V66 decodes all 27 ORIGINAL instructions including those
forms, branch targets, nested hardware loops and the final endloop marker.
The 108 source-generated bytes must match the user-provided private original.
"""
from __future__ import annotations
import argparse
import importlib.util
from pathlib import Path
import struct
import subprocess
import tempfile

FILE_OFFSET=0x3eb8
PHYS=0x96c00eb8
SIZE=108
PREFIX=32
LLVM_BODY_START=24
LLVM_ASM='''.text
.global cdsp_copyfast
cdsp_copyfast:
{
 p0=cmp.eq(r2,#0)
 if(p0.new) jump:nt finish
 r0=memw(gp+##0xc0673260)
}
{
 p0=cmp.gt(r2,#32)
 if(!p0.new) jump:nt finish
}
{
 p0=cmp.eq(r0,#0)
 if(p0.new) jump:nt finish
 r3=#128
}
{
 r6=lsr(r2,#12)
 r4=add(r0,#8)
 r5=add(r1,#8)
}
{
 loop1(l1,r6)
 r7=##0x808020
}
l1:
{ l2fetch(r1,r7) }
{ loop0(l0,r3) }
l0:
{ dczeroa(r1) }
{
 r7:6=memd(r0++#16)
 r9:8=memd(r4++#16)
}
{
 memd(r1++#16)=r7:6
 memd(r5++#16)=r9:8
}
{
 r7:6=memd(r0++#16)
 r9:8=memd(r4++#16)
}
{
 nop
 memd(r1++#16)=r7:6
 memd(r5++#16)=r9:8
}
finish:
{ jumpr lr }
'''

EXPECTED=(
 'p0=cmp.eq(r2,#0x0);if(p0.new)jump:nt0x96c00f20',
 'immext(##0xc0673240)', 'r0=memw(gp+##0xc0673260)',
 'p0=cmp.gt(r2,##0x20)', 'if(!p0.new)jump:nt0x96c00f20',
 'p0=cmp.eq(r0,#0x0);if(p0.new)jump:nt0x96c00f20',
 'immext(##0x80)', 'r3=##0x80', 'r6=lsr(r2,#0xc)',
 'r4=add(r0,##0x8)', 'r5=add(r1,##0x8)',
 'loop1(0x96c00ef0,r6)', 'immext(##0x808000)', 'r7=##0x808020',
 'l2fetch(r1,r7)', 'loop0(0x96c00ef8,r3)', 'dczeroa(r1)',
 'r7:6=memd(r0++#0x10)', 'r9:8=memd(r4++#0x10)',
 'memd(r1++#0x10)=r7:6', 'memd(r5++#0x10)=r9:8',
 'r7:6=memd(r0++#0x10)', 'r9:8=memd(r4++#0x10)',
 'nop', 'memd(r1++#0x10)=r7:6', 'memd(r5++#0x10)=r9:8<endloop01',
 'jumprlr'
)

def import_helper(filename:str,label:str):
    spec=importlib.util.spec_from_file_location(label,Path(__file__).with_name(filename))
    if spec is None or spec.loader is None:raise ValueError('missing fixture helper')
    mod=importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod

def assemble(llvm_mc:Path)->bytes:
    with tempfile.TemporaryDirectory(prefix='cdsp-copyfast-') as d:
        asm=Path(d)/'copyfast.s';obj=Path(d)/'copyfast.o'
        asm.write_text(LLVM_ASM)
        subprocess.run([str(llvm_mc),'-triple=hexagon','-mcpu=hexagonv60',
                        '-filetype=obj','-o',str(obj),str(asm)],check=True)
        return import_helper('verify-cdsp-hexagon-entry.py','cdsp_elf_check').parse_elf32_text(obj.read_bytes())

def verify(llvm_mc:Path,rz_asm:Path,generated:Path,reference:Path|None)->None:
    raw=generated.read_bytes()
    if len(raw)!=SIZE:raise ValueError('source-generated cache copy must be 108 bytes')
    llvm=assemble(llvm_mc)
    if len(llvm)!=100:raise ValueError('LLVM independent fixture layout changed')
    body=raw[PREFIX:]
    llvm_body=llvm[LLVM_BODY_START:]
    if len(body)!=76 or len(llvm_body)!=76:raise ValueError('body size changed')
    for idx,(w,b) in enumerate(zip(struct.unpack('<19I',body),struct.unpack('<19I',llvm_body))):
        if idx in (15,16):
            if (w & ~0xc000)!=(b & ~0xc000) or (w & 0xc000)!=0x8000:
                raise ValueError(f'endloop01 marker/operand mismatch at offset {idx*4:#x}')
        elif w!=b:
            raise ValueError(f'ordinary LLVM opcode disagrees at file {FILE_OFFSET+PREFIX+idx*4:#x}')
    decoder=import_helper('verify-cdsp-tlb.py','cdsp_v66_full_decoder')
    actual=decoder.decode_rizin(rz_asm,raw,physical_address=PHYS)
    if tuple(actual)!=EXPECTED:raise ValueError(f'V66 decoded operations or loop targets mismatch: {actual}')
    if reference is not None:
        orig=reference.read_bytes()
        if orig[FILE_OFFSET:FILE_OFFSET+SIZE]!=raw:raise ValueError('CDSP cache copy differs from original reference')
    print('CDSP cache copy 108/108 exact private-reference bytes; 74/76 LLVM body bytes identical, remaining two endloop marker bytes checked by ISA fields; all 27 V66 words decoded by Rizin')

def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--llvm-mc',type=Path,required=True)
    p.add_argument('--rz-asm',type=Path,required=True)
    p.add_argument('--rust-output',type=Path,required=True)
    p.add_argument('--reference',type=Path)
    a=p.parse_args();verify(a.llvm_mc,a.rz_asm,a.rust_output,a.reference)
if __name__=='__main__':main()

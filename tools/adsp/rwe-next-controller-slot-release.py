"""Source-build ADSP controller slot release and bitmap cleanup [0x11c88,0x11d68).

LLVM6 generates 55 ordinary Hexagon words. The one V66-only read of SGP0
is installed using a checked, typed register encoder at the exact LLVM NOP
sentinel. OEM firmware is never used to manufacture emitted bytes.
"""
from __future__ import annotations
import argparse,hashlib,importlib.util,struct,sys
from pathlib import Path
import sys
T=Path(__file__).resolve().parent
if str(T) not in sys.path:sys.path.insert(0,str(T))
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from adsp_hexagon_v66 import SystemRegister,read_system_register
START=0x11c88;END=0x11d68;SIZE=END-START;PHYSICAL=0x8be0ec88
SOURCE=T/'rwe-next-controller-slot-release.S'
REFERENCE_SHA='4b579e5dc1333d634e5bdc93f3314e357e0e30dab7140833f6cc7aef086b1c1e'
READ_SGP0_AT=0x11c94
NOP=struct.pack('<I',0x7f00c000)

def render(llvm_mc:str)->bytes:
    spec=importlib.util.spec_from_file_location('hex_asm',T/'emit-adsp-entry.py')
    if not spec or not spec.loader:raise RuntimeError('Missing Hexagon LLVM6 tool')
    m=importlib.util.module_from_spec(spec);spec.loader.exec_module(m)
    out=bytearray(m.assemble(llvm_mc,SOURCE,SIZE))
    where=READ_SGP0_AT-START
    if out[where:where+4]!=NOP:
        raise m.AdspError('SGP0 read requires an exact full-packet LLVM sentinel')
    out[where:where+4]=struct.pack('<I',read_system_register(2,SystemRegister.SGP0))
    if any(out[i:i+4]==NOP for i in range(0,SIZE,4)):
        raise m.AdspError('Unexpected unresolved privileged placeholder')
    return bytes(out)

def verify(reference:bytes,out:bytes)->None:
    if hashlib.sha256(reference).hexdigest()!=REFERENCE_SHA:
        raise ValueError('Wrong ADSP source image revision')
    if len(out)!=SIZE or out!=reference[START:END]:
        raise ValueError('Controller slot-release source differs from reference')

def main()->int:
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--llvm-mc',required=True)
    p.add_argument('--reference',type=Path);p.add_argument('--output',type=Path,required=True)
    a=p.parse_args();out=render(a.llvm_mc)
    if a.reference:verify(a.reference.read_bytes(),out)
    a.output.write_bytes(out)
    print(f'ADSP controller-slot release: {SIZE} source-generated bytes '
          f'[0x{START:x},0x{END:x}), physical 0x{PHYSICAL:x}; '
          f'sha256={hashlib.sha256(out).hexdigest()}')
    return 0
if __name__=='__main__':raise SystemExit(main())

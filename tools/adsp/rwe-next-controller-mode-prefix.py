"""Source-rebuild ADSP controller mode dispatch prefix [0x139e0,0x13a2c).

Program-register read SGP0 uses a checked V66 field constructor. The
source exposes the normal return and the branch targets to later, not-yet-
reconstructed branches; no OEM opcodes or signed firmware are copied.
"""
from __future__ import annotations
import argparse, hashlib, importlib.util, struct, sys
from pathlib import Path
import sys
T=Path(__file__).resolve().parent
if str(T) not in sys.path:sys.path.insert(0,str(T))
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from adsp_hexagon_v66 import SystemRegister, read_system_register, packet_continuation
START=0x139e0;END=0x13a2c;SIZE=END-START;PHYSICAL=0x8be109e0
SGP0_AT=0x139ec
SOURCE=T/'rwe-next-controller-mode-prefix.S'
REFERENCE_SHA='4b579e5dc1333d634e5bdc93f3314e357e0e30dab7140833f6cc7aef086b1c1e'
NOP=struct.pack('<I',0x7f00c000)

def render(llvm_mc:str)->bytes:
 spec=importlib.util.spec_from_file_location('hex_llvm6',T/'emit-adsp-entry.py')
 if not spec or not spec.loader:raise RuntimeError('Hexagon LLVM6 source assembler missing')
 emitter=importlib.util.module_from_spec(spec);spec.loader.exec_module(emitter)
 out=bytearray(emitter.assemble(llvm_mc,SOURCE,SIZE))
 offset=SGP0_AT-START
 if out[offset:offset+4]!=NOP:raise emitter.AdspError('SGP0 placeholder must be a standalone NOP')
 struct.pack_into('<I',out,offset,read_system_register(2,SystemRegister.SGP0))
 # Three source-assembled instructions are the first word of larger OEM
 # packets. Update only the two parse bits; leave all operand bits intact.
 for location in (0x139e0,0x139f8,0x13a04):
  i=location-START
  original=struct.unpack_from('<I',out,i)[0]
  changed=packet_continuation(original)
  if (original & ~0xc000)!=(changed & ~0xc000):
   raise emitter.AdspError('Packet adjustment modified non-parse bits')
  struct.pack_into('<I',out,i,changed)
 if any(out[i:i+4]==NOP for i in range(0,SIZE,4)):
  raise emitter.AdspError('Unresolved privileged placeholder')
 return bytes(out)

def verify(reference:bytes,generated:bytes)->None:
 if hashlib.sha256(reference).hexdigest()!=REFERENCE_SHA:raise ValueError('Unexpected ADSP reference revision')
 if len(generated)!=SIZE or reference[START:END]!=generated:raise ValueError('Controller mode prefix differs from reference')
 if reference[START-4:START]!=b'\x00'*4:raise ValueError('Missing 4-byte alignment fill preceding prefix')

def main()->int:
 p=argparse.ArgumentParser(description=__doc__);p.add_argument('--llvm-mc',required=True)
 p.add_argument('--reference',type=Path);p.add_argument('--output',type=Path,required=True)
 a=p.parse_args();out=render(a.llvm_mc)
 if a.reference:verify(a.reference.read_bytes(),out)
 a.output.write_bytes(out)
 print(f'ADSP mode prefix {SIZE} source-generated bytes [0x{START:x},0x{END:x}), physical 0x{PHYSICAL:x}, sha256={hashlib.sha256(out).hexdigest()}')
 return 0
if __name__=='__main__':raise SystemExit(main())

"""Reconstruct the ADSP controller-state guard and error-return packets.

All instructions are compiled from Hexagon assembly sources; LLVM6's
canonical duplex scheduling differs in the error packet, so the exact
R2-zero continuation and R0/restore duplex are source-assembled separately.
No proprietary instructions or OEM bytes are copied into generated output.
"""
from __future__ import annotations
import argparse, hashlib, importlib.util, struct, sys
from pathlib import Path
import sys

TOOLS=Path(__file__).resolve().parent
if str(TOOLS) not in sys.path:sys.path.insert(0,str(TOOLS))
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from adsp_hexagon_v66 import packet_continuation
FILE_START=0x10f64
FILE_END=0x10fe8
SIZE=FILE_END-FILE_START
PHYSICAL_START=0x8be0df64
REFERENCE_SHA256='4b579e5dc1333d634e5bdc93f3314e357e0e30dab7140833f6cc7aef086b1c1e'
SOURCE=TOOLS/'rwe-next-controller-state.S'
ZERO_SCALAR=TOOLS/'rwe-next-r2-zero.S'
RESTORE_DUPLEX=TOOLS/'rwe-next-error-duplex.S'

def previous():
    p=TOOLS.parent/'emit-adsp-entry.py'
    s=importlib.util.spec_from_file_location('adsp_bootstrap_emit',p)
    if not s or not s.loader:raise RuntimeError('Missing Hexagon source compiler')
    m=importlib.util.module_from_spec(s);s.loader.exec_module(m)
    return m

def render(llvm_mc:str)->bytes:
    m=previous()
    source=bytearray(m.assemble(llvm_mc,SOURCE,SIZE))
    # LLVM6 pairs a regular R0=#36 with a compressed R2=#0 + restore.
    # The actual Hexagon packet places regular R2=#0 before a source-assembled
    # R0=#36+R17:16 restore duplex. Require the exact *LLVM-produced* surrogate
    # instructions before changing the packet, so source changes cannot quietly
    # overwrite unrelated instructions.
    a,b=(0x10fd0-FILE_START,0x10fd4-FILE_START)
    if (struct.unpack_from('<I',source,a)[0],struct.unpack_from('<I',source,b)[0])!=(0x78004480,0x48023e04):
        raise m.AdspError('Canonical LLVM duplex scheduling changed; refusing replacement')
    zero=m.assemble(llvm_mc,ZERO_SCALAR,4)
    duplex=m.assemble(llvm_mc,RESTORE_DUPLEX,4)
    source[a:a+4]=struct.pack('<I',packet_continuation(struct.unpack('<I',zero)[0]))
    source[b:b+4]=duplex
    if len(source)!=SIZE:raise m.AdspError('Hexagon rebuilt length changed')
    return bytes(source)

def verify(original:bytes,rebuilt:bytes)->None:
    if hashlib.sha256(original).hexdigest()!=REFERENCE_SHA256:
        raise ValueError('Wrong ADSP reference firmware revision')
    if len(rebuilt)!=SIZE:
        raise ValueError(f'Expected {SIZE} generated bytes')
    expected=original[FILE_START:FILE_END]
    if rebuilt!=expected:
        first=next((i for i,(x,y) in enumerate(zip(rebuilt,expected)) if x!=y),0)
        raise ValueError(f'Controller state bytes differ at file 0x{FILE_START+first:x}')

def main()->int:
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--llvm-mc',required=True)
    p.add_argument('--reference',type=Path)
    p.add_argument('--output',type=Path,required=True)
    a=p.parse_args()
    b=render(a.llvm_mc)
    if a.reference:verify(a.reference.read_bytes(),b)
    a.output.write_bytes(b)
    print(f'ADSP Hexagon controller-state: {len(b)} exact source-built bytes '
          f'file [0x{FILE_START:x},0x{FILE_END:x}) physical '
          f'[0x{PHYSICAL_START:x},0x{PHYSICAL_START+SIZE:x}) '
          f'sha256={hashlib.sha256(b).hexdigest()}')
    return 0
if __name__=='__main__':sys.exit(main())

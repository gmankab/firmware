"""Emit the original ADSP table initializer [0x11ae0,0x11ba0) from source.

Two hardware loops update multiple controller tables. LLVM6 emits the
instruction operands/packet contents. Its packetizer closes one packet a
word earlier than the hardware code: the ``r3=##`` word must be a packet
*continuation* so the following p0/new-value duplex closes that packet.
Only its two parse bits are updated, checked against a known source layout.
No opcode bytes are copied from the firmware.
"""
from __future__ import annotations
import argparse,hashlib,importlib.util,struct,sys
from pathlib import Path
TOOLS=Path(__file__).resolve().parent
if str(TOOLS) not in sys.path:sys.path.insert(0,str(TOOLS))
START=0x11ae0;END=0x11ba0;SIZE=END-START;PHYSICAL=0x8be0eae0
SOURCE=TOOLS/'rwe-next-controller-table-init.S'
REFERENCE_SHA='4b579e5dc1333d634e5bdc93f3314e357e0e30dab7140833f6cc7aef086b1c1e'
FIELD_AT=0x11b40
PARSE_MASK=0x0000c000
PACKET_END=0x0000c000
PACKET_CONTINUE=0x00004000

def render(llvm_mc:str)->bytes:
    spec=importlib.util.spec_from_file_location('adsp_emit',TOOLS.parent/'emit-adsp-entry.py')
    if not spec or not spec.loader:raise RuntimeError('Missing Hexagon LLVM source assembler')
    emitter=importlib.util.module_from_spec(spec);spec.loader.exec_module(emitter)
    out=bytearray(emitter.assemble(llvm_mc,SOURCE,SIZE))
    offset=FIELD_AT-START
    ins=struct.unpack_from('<I',out,offset)[0]
    # The LLVM6 source packet contains r3=##0xf0026c30. Its immediate field
    # and all non-parse bits are generated by the assembler and stay unchanged.
    if (ins & PARSE_MASK)!=PACKET_END:
        raise emitter.AdspError('Expected exactly one LLVM6 packet-end marker')
    adjusted=(ins & ~PARSE_MASK)|PACKET_CONTINUE
    struct.pack_into('<I',out,offset,adjusted)
    return bytes(out)

def verify(reference:bytes,built:bytes)->None:
    if hashlib.sha256(reference).hexdigest()!=REFERENCE_SHA:
        raise ValueError('Unexpected original ADSP image revision')
    if len(built)!=SIZE or built!=reference[START:END]:
        raise ValueError('Controller table init fragment differs from reference')
    # The neighboring executable ending at 0x119c0 is separated by real data.
    # No data bytes or linker zeros count as reconstructed executable source.
    gap=reference[0x119c0:START]
    if b'QURT kernel started' not in gap or gap[-32:]!=bytes(32):
        raise ValueError('Expected ADSP diagnostics and zero fill before this function')

def main()->int:
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--llvm-mc',required=True)
    p.add_argument('--reference',type=Path)
    p.add_argument('--output',type=Path,required=True)
    a=p.parse_args();out=render(a.llvm_mc)
    if a.reference:verify(a.reference.read_bytes(),out)
    a.output.write_bytes(out)
    print(f'ADSP table initializer {len(out)} source-built bytes file '
          f'[0x{START:x},0x{END:x}) physical [0x{PHYSICAL:x},'
          f'0x{PHYSICAL+SIZE:x}) sha256={hashlib.sha256(out).hexdigest()}')
    return 0

if __name__=='__main__':raise SystemExit(main())

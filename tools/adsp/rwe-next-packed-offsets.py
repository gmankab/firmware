"""Source-assemble two Hexagon controller-address compression helpers.

Exactly 92 bytes are generated. The following 12 zero bytes are linker fill,
not independently reconstructed executable or an inlined OEM payload.
"""
from __future__ import annotations
import argparse,hashlib,importlib.util,sys
from pathlib import Path
SOURCE=Path(__file__).resolve().parents[2]/'sources/xiaomi-nabu/adsp/rwe/rwe-next-packed-offsets.S'
FILE_START=0x11108
FILE_END=0x11164
SIZE=FILE_END-FILE_START
FILL_START=FILE_END
FILL_END=0x11170
PHYSICAL_START=0x8be0e108
REFERENCE_SHA256='4b579e5dc1333d634e5bdc93f3314e357e0e30dab7140833f6cc7aef086b1c1e'

def base():
    spec=importlib.util.spec_from_file_location('adsp_core',Path(__file__).resolve().parents[1]/'emit-adsp-entry.py')
    if not spec or not spec.loader:raise RuntimeError('Missing Hexagon source assembler')
    m=importlib.util.module_from_spec(spec);spec.loader.exec_module(m);return m

def render(llvm_mc:str)->bytes:
    return base().assemble(llvm_mc,SOURCE,SIZE)

def verify(reference:bytes,built:bytes)->None:
    if hashlib.sha256(reference).hexdigest()!=REFERENCE_SHA256:
        raise ValueError('Wrong ADSP reference revision')
    if len(built)!=SIZE or built!=reference[FILE_START:FILE_END]:
        raise ValueError('Packed offset source-generated bytes differ')
    if reference[FILL_START:FILL_END]!=b'\x00'*(FILL_END-FILL_START):
        raise ValueError('Packed offset trailing linker fill differs')

def main()->int:
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--llvm-mc',required=True)
    p.add_argument('--reference',type=Path)
    p.add_argument('--output',type=Path,required=True)
    a=p.parse_args();b=render(a.llvm_mc)
    if a.reference:verify(a.reference.read_bytes(),b)
    a.output.write_bytes(b)
    print(f'ADSP source-built offset helpers {len(b)} bytes file '
          f'[0x{FILE_START:x},0x{FILE_END:x}) physical '
          f'[0x{PHYSICAL_START:x},0x{PHYSICAL_START+SIZE:x}) '
          f'sha256={hashlib.sha256(b).hexdigest()}')
    return 0
if __name__=='__main__':sys.exit(main())

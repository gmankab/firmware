"""Source-assemble the ADSP controller-slot removal/search function.

All 91 Hexagon V66 words are generated by LLVM6 from original-source-style
mnemonic packets. Three source pieces are concatenated; no raw firmware
instructions or signature bytes appear in this emitter. A separate four-byte
linker gap precedes the routine and is not considered program source.
"""
from __future__ import annotations
import argparse,hashlib,importlib.util,sys
from pathlib import Path
T=Path(__file__).resolve().parent
ASSEMBLY_DIR=Path(__file__).resolve().parents[2]/'sources/xiaomi-nabu/adsp/rwe'
START=0x12430
END=0x1259c
SIZE=END-START
PHYSICAL=0x8be0f430
REFERENCE_SHA='4b579e5dc1333d634e5bdc93f3314e357e0e30dab7140833f6cc7aef086b1c1e'
PARTS=(
    ('rwe-next-controller-slot-remove-prefix.S',0x68),
    ('rwe-next-controller-slot-remove-search.S',0x7c),
    ('rwe-next-controller-slot-remove-final.S',0x88),
)

def render(llvm_mc:str)->bytes:
    spec=importlib.util.spec_from_file_location('adsp_entry',T/'emit-adsp-entry.py')
    if not spec or not spec.loader:raise RuntimeError('Missing Hexagon LLVM6 emitter')
    m=importlib.util.module_from_spec(spec);spec.loader.exec_module(m)
    result=b''.join(m.assemble(llvm_mc,ASSEMBLY_DIR/name,length) for name,length in PARTS)
    if len(result)!=SIZE:raise m.AdspError('Wrong controller-slot release length')
    return result

def verify(reference:bytes,built:bytes)->None:
    if hashlib.sha256(reference).hexdigest()!=REFERENCE_SHA:
        raise ValueError('Wrong pinned ADSP reference revision')
    if len(built)!=SIZE or built!=reference[START:END]:
        raise ValueError('Controller slot-release function differs from original reference')
    if reference[START-4:START]!=bytes(4):
        raise ValueError('Expected four bytes of linker fill before function')

def main()->int:
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--llvm-mc',required=True);p.add_argument('--reference',type=Path)
    p.add_argument('--output',type=Path,required=True);a=p.parse_args()
    b=render(a.llvm_mc)
    if a.reference:verify(a.reference.read_bytes(),b)
    a.output.write_bytes(b)
    print(f'ADSP controller slot search/remove {len(b)} exact source-built bytes '
          f'file [{START:#x},{END:#x}), physical [{PHYSICAL:#x},{PHYSICAL+SIZE:#x}), '
          f'sha256={hashlib.sha256(b).hexdigest()}')
    return 0
if __name__=='__main__':raise SystemExit(main())

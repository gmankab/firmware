LLVM_MAP=[0x477c,0x4780,0x4784,0x4788,0x478c,0x4790,0x4794,0x4798,
          0x47a0,0x47a4,0x47ac,0x47b0,0x47b8,0x47bc,0x47c4,0x47c8,
          0x47d0,0x47d8,0x47e0,0x47e4,0x47f0,0x47f8,0x4804,0x480c]

def elf_text(path:Path)->bytes:
    src=Path(__file__).with_name('verify-cdsp-hexagon-entry.py')
    spec=importlib.util.spec_from_file_location('agent20_context_elf',src)
    assert spec and spec.loader
    mod=importlib.util.module_from_spec(spec);spec.loader.exec_module(mod)
    return mod.parse_elf32_text(path.read_bytes())

def verify(llvm:Path,rz:Path,binary:Path,reference:Path):
    code=binary.read_bytes()
    if len(code)!=LEN or reference.read_bytes()[START:START+LEN]!=code:
        raise ValueError('CDSP context source/length/reference mismatch')
    p=subprocess.run([str(rz),'-a','hexagon','-b','32','-o',hex(PHYSICAL),'-D',code.hex()],capture_output=True,text=True,check=True)
    insn={}
    for row in p.stdout.splitlines():
        match=re.match(r'^0x([a-fA-F0-9]+)\s+4\s+[a-fA-F0-9]{8}\s+[?\\/\[|]\s+(.*)',row)
        if match:insn[int(match[1],16)]=''.join(match[2].lower().split())
    if len(insn)!=LEN//4:raise ValueError(f'Only {len(insn)} of {LEN//4} context instructions decoded')
    for fileoffset,text in EXPECTED.items():
        got=insn.get(PHYSICAL+fileoffset-START,'')
        if text not in got:raise ValueError(f'Incorrect V66 semantic at {fileoffset:#x}: {got}, expected {text}')
    with tempfile.TemporaryDirectory(prefix='hexagon-context-') as tmp:
        src=Path(tmp)/'source.s';obj=Path(tmp)/'source.o';src.write_text(LLVM_SOURCE)
        subprocess.run([str(llvm),'-triple=hexagon','-mcpu=hexagonv60','-filetype=obj','-o',str(obj),str(src)],capture_output=True,text=True,check=True)
        oem=elf_text(obj)
    if len(oem)!=len(LLVM_MAP)*4:raise ValueError('LLVM rearranged context packet count unexpectedly')
    for i,offset in enumerate(LLVM_MAP):
        actual=int.from_bytes(code[offset-START:offset-START+4],'little')
        independent=int.from_bytes(oem[4*i:4*i+4],'little')
        if (actual&~0xc000)!=(independent&~0xc000):
            raise ValueError(f'Hexagon LLVM6 independently encoded different word at {offset:#x}')
    print('CDSP context save: 188 exact generated bytes; 47 Rizin V66 words; 24 LLVM6 independent register/duplex encodings; privileged register snapshots decoder-confirmed only.')

def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--llvm-mc',required=True,type=Path)
    p.add_argument('--rz-asm',required=True,type=Path)
    p.add_argument('--rust-output',required=True,type=Path)
    p.add_argument('--reference',required=True,type=Path)
    a=p.parse_args();verify(a.llvm_mc,a.rz_asm,a.rust_output,a.reference)
if __name__=='__main__':main()

"""Independent Hexagon V66/LLVM6 checks for the CDSP supervisor snapshot.

The original reference is private and read only. Exact LLVM6 word matches
are limited to forms that LLVM6 assembles with identical V66 packet markers;
unsupported privileged-register transfers are Rizin/reference-verified only.
"""
from pathlib import Path
import argparse
import hashlib
import importlib.util
import re
import subprocess
import tempfile

FILE_START=0x4f1c
FILE_END=0x4f64
PHYS_START=0x96c01f1c
REFERENCE_SHA256='febeae7b8e47bad4eeabc159a3c24b74cda26dfa12b384c31de5de30817e06ea'
EXPECTED=[
    'immext(##0x30780)',
    'call0x96c326d0',
    'r1=ssr',
    'r0=elr',
    'immext(##0xfe016e00)',
    'memw(r2=##0xfe016e10)=r1',
    'r1=diag',
    'immext(##0xfe016e00)',
    'memw(gp+##0xfe016e14)=r0',
    'r0=syscfg',
    'immext(##0xfe037240)',
    'memw(r3=##0xfe037250)=r1',
    'immext(##0xfe024d00)',
    'r1=memw(gp+##0xfe024d00)',
    'immext(##0xfe016e00)',
    'memw(gp+##0xfe016e18)=r0',
    'dccleana(r2)',
    'dccleana(r3)',
]
# These unprivileged V60 instructions independently assemble byte-identically
# with the target packet markers; GP-relative forms use different LLVM6
# shortening behavior and are NOT counted as exact LLVM matches.
LLVM_SAMPLES=[
    ('{ memw(r2=##0xfe016e10)=r1 }',[4,5]),
    ('{ memw(r3=##0xfe037250)=r1 }',[10,11]),
    ('{ dccleana(r2) }',[16]),
    ('{ dccleana(r3) }',[17]),
]


def assemble(llvm:Path, asm:str)->bytes:
    with tempfile.TemporaryDirectory(prefix='cdsp35-independent-') as name:
        p=Path(name)
        (p/'code.s').write_text('.text\n.global verify\nverify:\n'+asm+'\n')
        proc=subprocess.run([str(llvm),'-triple=hexagon','-mcpu=hexagonv60',
            '-filetype=obj','-o',str(p/'code.o'),str(p/'code.s')],
            capture_output=True,text=True)
        if proc.returncode:
            raise ValueError('independent LLVM6 assembly failed: '+proc.stderr)
        loader=Path(__file__).with_name('verify-cdsp-hexagon-entry.py')
        spec=importlib.util.spec_from_file_location('agent09_snapshot_elf',loader)
        mod=importlib.util.module_from_spec(spec)
        spec.loader.exec_module(mod)
        return mod.parse_elf32_text((p/'code.o').read_bytes())


def verify(args):
    reference=args.reference.read_bytes()
    if hashlib.sha256(reference).hexdigest()!=REFERENCE_SHA256:
        raise ValueError('CDSP original SHA-256 does not match pinned source revision')
    source=args.rust_output.read_bytes()
    if len(source)!=FILE_END-FILE_START or source!=reference[FILE_START:FILE_END]:
        raise ValueError('72 generated bytes differ from the pinned CDSP reference')
    text=subprocess.run([str(args.rz_asm),'-a','hexagon','-b','32',
       '-o',hex(PHYS_START),'-D',source.hex()],capture_output=True,text=True,check=True).stdout
    records=[]
    for line in text.splitlines():
        match=re.match(r'^0x([0-9a-fA-F]+)\s+4\s+[0-9a-fA-F]{8}\s+[?/\\\[|]\s+(.*)',line)
        if match:records.append((int(match[1],16),''.join(match[2].lower().split())))
    if len(records)!=18:raise ValueError(f'Rizin decoded {len(records)} rather than 18 words')
    for i,((addr,actual),want) in enumerate(zip(records,EXPECTED)):
        if addr!=PHYS_START+i*4 or want not in actual:
            raise ValueError(f'V66 decode mismatch at {addr:#x}: {actual} does not contain {want}')
    match_count=0
    for asm,indices in LLVM_SAMPLES:
        compiled=assemble(args.llvm_mc,asm)
        if len(compiled)!=4*len(indices):
            raise ValueError(f'Independent LLVM6 returned unexpected size for {asm}: {len(compiled)}')
        for ix,target in enumerate(indices):
            if compiled[ix*4:ix*4+4]!=source[target*4:target*4+4]:
                raise ValueError(f'LLVM6 mismatch for {asm} at file {FILE_START+target*4:#x}')
            match_count+=1
    print('CDSP snapshot:',len(source),'exact reference bytes,',len(records),
          'V66 decoded words,',match_count,
          'exact independently LLVM6-assembled ordinary instruction words;'
          'privileged transfers decoder/reference verified only')

if __name__=='__main__':
    p=argparse.ArgumentParser(description=__doc__)
    for name in ('reference','rust-output','rz-asm','llvm-mc'):
        p.add_argument('--'+name,required=True,type=Path)
    verify(p.parse_args())

"""Check reference-exact CDSP interrupt-debug bytes, V66 decode, LLVM6 forms.

Privileged ISDBEN/CFGBASE and physical-addressing instructions are Rizin
corroborated, NOT falsely claimed LLVM6-reproducible.
"""
import argparse, importlib.util, re, subprocess, tempfile
from pathlib import Path

FILE_OFFSET=0x4568
PHYSICAL=0x96c01568
SIZE=0x58
EXPECTED={
    0x4568:'r1=isdben',
    0x456c:'p0=tstbit(r1,#0x2)',
    0x4570:'if(!p0.new)jump:t0x96c015b0',
    0x4574:'r1=cfgbase',
    0x4578:'r25=##0x0',
    0x457c:'r1=insert(r25,#0xc,#0x14)',
    0x4580:'r1=asl(r1,#0x5)',
    0x4588:'r1=memw_phys(r0,r1)',
    0x4598:'r1=add(r1,##-0x100)',
    0x45a4:'r24=memw(r23+##-0x1fd92f4)',
    0x45a8:'r0=and(r1,r24)',
    0x45ac:'p0=cmp.eq(r0,#0x0);if(p0.new)jump:t0x96c015c0',
    0x45b4:'isdben=r1',
    0x45b8:'isync',
    0x45bc:'brkpt',
}
ASM='''.text
.global start
start:
{ r1 = insert(r25,#12,#20) }
{ r1 = asl(r1,#5) }
{ r0 = #8 }
{ r1 = add(r1,#-256) }
{ r0 = and(r1,r24) }
{ r1 = #1 }
'''

def extract_elf(path:Path)->bytes:
    src=Path(__file__).with_name('verify-cdsp-hexagon-entry.py')
    spec=importlib.util.spec_from_file_location('agent20_cdsp_debug_elf',src)
    assert spec and spec.loader
    mod=importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod.parse_elf32_text(path.read_bytes())

def main():
    a=argparse.ArgumentParser(description=__doc__)
    a.add_argument('--llvm-mc',type=Path,required=True)
    a.add_argument('--rz-asm',type=Path,required=True)
    a.add_argument('--rust-output',type=Path,required=True)
    a.add_argument('--reference',type=Path,required=True)
    args=a.parse_args()
    generated=args.rust_output.read_bytes()
    if len(generated)!=SIZE:raise ValueError(f'Expected {SIZE} bytes, got {len(generated)}')
    ref=args.reference.read_bytes()
    if ref[FILE_OFFSET:FILE_OFFSET+SIZE]!=generated:
        raise ValueError('CDSP interrupt-debug bytes differ from private pinned reference')
    p=subprocess.run([str(args.rz_asm),'-a','hexagon','-b','32','-o',hex(PHYSICAL),'-D',generated.hex()],capture_output=True,text=True,check=True)
    rows={}
    for line in p.stdout.splitlines():
        m=re.match(r'^0x([a-fA-F0-9]+)\s+4\s+[a-fA-F0-9]{8}\s+[?\\/\[|]\s+(.*)',line)
        if m:rows[int(m[1],16)]=''.join(m[2].lower().split())
    if len(rows)!=SIZE//4:raise ValueError(f'Only {len(rows)} of {SIZE//4} instructions decoded')
    for off,expected in EXPECTED.items():
        value=rows.get(PHYSICAL+(off-FILE_OFFSET),'')
        if expected not in value:
            raise ValueError(f'{off:#x}: expected {expected}, Rizin: {value}')
    with tempfile.TemporaryDirectory(prefix='cdsp-intdebug-') as temp:
        src=Path(temp)/'probe.s';obj=Path(temp)/'probe.o';src.write_text(ASM)
        subprocess.run([str(args.llvm_mc),'-triple=hexagon','-mcpu=hexagonv60','-filetype=obj','-o',str(obj),str(src)],capture_output=True,text=True,check=True)
        llvm=extract_elf(obj)
    offsets=(0x457c,0x4580,0x4584,0x4598,0x45a8,0x45b0)
    for i,off in enumerate(offsets):
        actual=int.from_bytes(generated[off-FILE_OFFSET:off-FILE_OFFSET+4],'little')
        independent=int.from_bytes(llvm[i*4:i*4+4],'little')
        if actual&~0xc000!=independent&~0xc000:
            raise ValueError(f'LLVM6 mismatch in supported scalar encoding at {off:#x}')
    print('CDSP interrupt-debug: 88/88 exact source-generated bytes; 22 V66 decoded words; 6 independent LLVM6 scalar encodings. Privileged instructions decoder-correlated only.')
if __name__=='__main__':main()

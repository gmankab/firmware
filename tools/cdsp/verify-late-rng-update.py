"""Independently verify complete CDSP seeded-update V66 routine.

The semantic LLVM6 source assembled with the same instructions has 136 bytes,
but LLVM6 reschedules the extended GP assignment and changes multiple packet
markers and some branch placements. Identical matching opcode words are
checked separately; the *original* packet structure and call targets are
verified with Rizin V66, not assumed to be identical to LLVM6 output.
"""
from __future__ import annotations
import argparse, importlib.util, re, subprocess, tempfile
from pathlib import Path
SOURCE_DIR=Path(__file__).resolve().parents[2]/'sources/xiaomi-nabu/cdsp/late'

FILE_OFFSET=0x563c0
FILE_SIZE=0x88
RWE_START=0x56000
RWE_END=0x56448
PHYS=0x96cc83c0

def words(data:bytes)->list[int]:
    if len(data)%4:raise ValueError('A Hexagon V66 code region is 32-bit word aligned')
    return [int.from_bytes(data[i:i+4],'little') for i in range(0,len(data),4)]

def load_elf_code(data:bytes)->bytes:
    loader=Path(__file__).with_name('verify-cdsp-hexagon-entry.py')
    spec=importlib.util.spec_from_file_location('cdsp_agent20_10_independent_elf_loader',loader)
    if spec is None or spec.loader is None:raise ValueError('ELF parser unavailable')
    impl=importlib.util.module_from_spec(spec)
    spec.loader.exec_module(impl)
    return impl.parse_elf32_text(data)

def verify(llvm:Path,rz:Path,generated:Path,reference:Path,
           prefix:Path|None=None,whole:Path|None=None)->None:
    actual=generated.read_bytes()
    ref=reference.read_bytes()
    if len(actual)!=FILE_SIZE or actual!=ref[FILE_OFFSET:FILE_OFFSET+FILE_SIZE]:
        raise ValueError('CDSP seed update 136 generated bytes are not byte-identical')
    if whole is not None:
        entire=whole.read_bytes()
        if len(entire)!=0x128 or entire != ref[0x56320:RWE_END]:
            raise ValueError('CDSP 296-byte full seed function mismatch')
        if entire[-FILE_SIZE:]!=actual:raise ValueError('Seed-function tail differs from emitted update')
    if prefix is not None:
        data=prefix.read_bytes()
        if len(data)!=RWE_END-RWE_START or data!=ref[RWE_START:RWE_END]:
            raise ValueError('CDSP contiguous RWE prefix through RNG return mismatch')
        if data[-FILE_SIZE:]!=actual:raise ValueError('RWE emitted prefix does not embed update')
        # Earlier callbacks intentionally have 32 bytes of linker layout NOP,
        # *not* an independently authored program. Do not count as code.
    with tempfile.TemporaryDirectory(prefix='hexagon_rng_update_') as d:
        obj=Path(d)/'rng-update.o'
        fixture=SOURCE_DIR / 'late-rwe-seed-update.s'
        subprocess.run([str(llvm),'-triple=hexagon','-mcpu=hexagonv60',
                        '-filetype=obj',str(fixture),'-o',str(obj)],
                       capture_output=True,text=True,check=True)
        independent=load_elf_code(obj.read_bytes())[0x3c0:]
    if len(independent)!=FILE_SIZE:raise ValueError('Expected exactly 136 LLVM6 semantic bytes')
    a,b=words(actual),words(independent)
    pair_indices=[(1,1),(2,2),(4,4),(5,5),(6,6),(8,9),(9,10),(10,8),
        (11,11),(12,12),(13,13),(14,14),(15,15),(16,16),(18,18),
        (19,19),(20,20),(21,21),(23,24),(25,25),(29,29),
        (30,30),(31,31),(33,33)]
    for x,y in pair_indices:
        if a[x]!=b[y]:raise ValueError(f'LLVM6 semantic mismatch: original word {x}, LLVM word {y}')
    dec=subprocess.run([str(rz),'-a','hexagon','-b','32',
                        '-o',hex(PHYS),'-D',actual.hex()],
                        capture_output=True,text=True,check=True).stdout
    rows=[l for l in dec.splitlines() if l.startswith('0x')]
    if len(rows)!=34 or any('invalid' in s.lower() for s in rows):
        raise ValueError(f'Rizin decoded {len(rows)}/34 valid Hexagon words')
    normalized='\n'.join(rows).lower().replace(' ','')
    features=['r2^=asl(r2,#0x3)','r3^=asl(r3,#0xd)',
       'r24=insert(r3,#0xd,#0x0)','r6=insert(r2,#0x15,#0x0)',
       'memw(r19+##0x0)=r24.new','memw(r20+##0x0)=r6.new',
       'memw(r18+##0x0)=r3.new','call0x96dc0680',
       'if(p0.new)jump:t0x96cc8368','if(!p0.new)memw(sp+##0x4)=r24',
       'call0x96dc4acc','lr:fp=dealloc_return']
    for f in features:
        if f not in normalized:raise ValueError('Rizin did not confirm feature '+f)
    print('PASS original CDSP MBN: exactly 136 source-generated seed-update bytes, zero differences')
    print(f'PASS independent LLVM6: {len(pair_indices)} unchanged instruction words; compiler-specific packet scheduling recorded')
    print('PASS Rizin V66: all 34 original-order instruction words, both physical call targets and conditional backward branch')
    if whole:print('PASS full seeded function: 296 executable bytes')
    if prefix:print('PASS contiguous RWE file prefix: 1096 bytes (1064 executable + 32 layout NOP/fill)')

if __name__=='__main__':
    p=argparse.ArgumentParser(description=__doc__)
    for field in ['llvm-mc','rz-asm','generated','reference','prefix','whole']:
        p.add_argument('--'+field,type=Path,required=field not in ('prefix','whole'))
    opts=p.parse_args()
    verify(opts.llvm_mc,opts.rz_asm,opts.generated,opts.reference,opts.prefix,opts.whole)

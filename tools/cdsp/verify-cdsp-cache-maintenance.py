"""Independent LLVM6/Rizin validation of Hexagon V66 cache maintenance.

LLVM6 assembles all ordinary cache-loop/branch packets (16 of 22 words).
Six unsupported V66-only cache/special-register instructions are substituted
by nops solely in the LLVM test fixture; Rizin decodes the original six and
all packet markers. A reference comparison covers all 88 generated bytes.
"""
from __future__ import annotations
import argparse
import importlib.util
from pathlib import Path
import struct
import subprocess
import tempfile

FILE_OFFSET=0x3f74
PHYSICAL_ADDRESS=0x96c00f74
LENGTH=88
LLVM_UNSUPPORTED=(5,10,12,17,19,20)
LLVM_ASM='''.text
.global cdsp_cache_maintenance
cdsp_cache_maintenance:
{ r22=#0 }
{ loop1(outer,#128) }
outer:
{ r21=r22 }
{ loop0(inner,#8) }
inner:
{ r21=add(r21,#1)
  nop }:endloop0
{ r22=add(r22,#32)
  nop }:endloop1
{ syncht }
{ nop }
{ syncht }
check:
{ nop }
{ p1=tstbit(r21,#31)
  if(p1.new) jump:t check }
{ syncht }
{ r21=clrbit(r21,#2) }
{ nop }
{ isync }
{ nop }
{ nop }
{ syncht }
'''
EXPECTED=(
 'r22=##0x0','loop1(0x96c00f7c,#0x80)','r21=r22',
 'loop0(0x96c00f84,#0x8)','r21=add(r21,##0x1)',
 'dccleaninvidx(r21)<endloop0','r22=add(r22,##0x20)',
 'nop','nop<endloop1','syncht','l2gcleaninv','syncht',
 'r21=syscfg','p1=tstbit(r21,#0x1f)',
 'if(p1.new)jump:t0x96c00fa4','syncht','r21=clrbit(r21,#0x2)',
 'syscfg=r21','isync','dckill','l2kill','syncht',
)

def loader(filename,name):
    spec=importlib.util.spec_from_file_location(name,Path(__file__).with_name(filename))
    assert spec and spec.loader
    m=importlib.util.module_from_spec(spec)
    spec.loader.exec_module(m)
    return m

def verify(llvm:Path,rz:Path,output:Path,reference:Path|None):
    got=output.read_bytes()
    if len(got)!=LENGTH:raise ValueError('CDSP cache-control code must be 88 bytes')
    parser=loader('verify-cdsp-hexagon-entry.py','cdsp_llvm_object')
    with tempfile.TemporaryDirectory(prefix='cdsp-clean-invalidate-') as tmp:
        src=Path(tmp)/'cache.s';obj=Path(tmp)/'cache.o'
        src.write_text(LLVM_ASM)
        subprocess.run([str(llvm),'-triple=hexagon','-mcpu=hexagonv60',
           '-filetype=obj','-o',str(obj),str(src)],check=True)
        independently_built=parser.parse_elf32_text(obj.read_bytes())
    if len(independently_built)!=LENGTH:raise ValueError('LLVM cache-loop fixture has altered length')
    generated_words=struct.unpack('<22I',got)
    independent_words=struct.unpack('<22I',independently_built)
    for i,(source,built) in enumerate(zip(generated_words,independent_words)):
        if i not in LLVM_UNSUPPORTED and source!=built:
            raise ValueError(f'LLVM-assembled instruction mismatch at CDSP {FILE_OFFSET+4*i:#x}')
    decoded=loader('verify-cdsp-tlb.py','cdsp_rizin').decode_rizin(rz,got,physical_address=PHYSICAL_ADDRESS)
    if tuple(decoded)!=EXPECTED:
        for i,(have,want) in enumerate(zip(decoded,EXPECTED)):
            if have!=want:raise ValueError(f'Rizin at index {i} expected {want}, got {have}')
        raise ValueError(f'V66 cache instruction count was {len(decoded)}, expected 22')
    if reference is not None:
        raw=reference.read_bytes()
        if raw[FILE_OFFSET:FILE_OFFSET+LENGTH]!=got:
            raise ValueError('CDSP V66 cache-maintenance generated bytes differ from reference')
    print('CDSP cache-maintenance 88/88 exact; 16/22 LLVM words identical, six V66-only cache/system words confirmed by Rizin; all 22 words decoded')

def main():
    ap=argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--llvm-mc',type=Path,required=True)
    ap.add_argument('--rz-asm',type=Path,required=True)
    ap.add_argument('--rust-output',type=Path,required=True)
    ap.add_argument('--reference',type=Path)
    x=ap.parse_args()
    verify(x.llvm_mc,x.rz_asm,x.rust_output,x.reference)
if __name__=='__main__':main()

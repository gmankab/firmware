"""Require independent exact LLVM6 assembly of the two CDSP record diagnostics."""
import argparse,hashlib,importlib.util,os,subprocess,tempfile
from pathlib import Path
START=0x56adc;END=0x56afc;LAYOUT_END=0x56b00;PHYS=0x96cc8adc
EXPECTED='febeae7b8e47bad4eeabc159a3c24b74cda26dfa12b384c31de5de30817e06ea'

def section(obj:bytes)->bytes:
 spec=importlib.util.spec_from_file_location('elf32_hexagon',Path(__file__).with_name('verify-cdsp-hexagon-entry.py'))
 if spec is None or spec.loader is None:raise ValueError('missing ELF32 assembler parser')
 m=importlib.util.module_from_spec(spec);spec.loader.exec_module(m)
 return m.parse_elf32_text(obj)

def check(a):
 ref=a.reference.read_bytes()
 if hashlib.sha256(ref).hexdigest()!=EXPECTED:raise ValueError('unexpected CDSP revision')
 gen=a.generated.read_bytes();prefix=a.prefix.read_bytes()
 if len(gen)!=32 or gen!=ref[START:END]:raise ValueError('original error packets do not match 32 generated bytes')
 if len(prefix)!=2816 or prefix!=ref[0x56000:LAYOUT_END]:raise ValueError('2816-byte RWE prefix mismatches')
 if prefix[-4:]!=b'\x00\xc0\x00\x7f':raise ValueError('four layout bytes must be one original NOP')
 with tempfile.TemporaryDirectory(prefix='cdsp-record-error-') as t:
  obj=Path(t)/'orig.o'
  subprocess.run([str(a.llvm_mc),'-triple=hexagon','-mcpu=hexagonv60','-filetype=obj',
      str(Path(__file__).with_name('late-controller-record-diagnostics.s')),
      '-o',str(obj)],check=True,stdout=subprocess.PIPE,stderr=subprocess.PIPE)
  reconstructed=section(obj.read_bytes())[0xadc:0xb00]
 if reconstructed!=gen+b'\x00\xc0\x00\x7f':raise ValueError('LLVM6 independent assembly differs from generated code and layout')
 env=os.environ.copy()
 lib=next((p/'ubuntu-runtime/build-deps-flat' for p in a.rz_asm.resolve().parents
           if (p/'ubuntu-runtime/build-deps-flat').is_dir()),None)
 if lib is not None:env['LD_LIBRARY_PATH']=str(lib)+':'+env.get('LD_LIBRARY_PATH','')
 proc=subprocess.run([str(a.rz_asm),'-a','hexagon','-b','32','-o',hex(PHYS),'-D',reconstructed.hex()],
      env=env,capture_output=True,text=True,check=True)
 lines=[x for x in proc.stdout.splitlines() if x.startswith('0x')]
 if len(lines)!=9 or any('invalid' in x.lower() for x in lines):raise ValueError('Rizin V66 diagnostic decoder differs')
 s='\n'.join(lines).lower().replace(' ','')
 for x in ['call0x96ccd8c4','r1=##0x16d','r1=##0x16e','r0=##-0x3fdd9e8b','nop']:
  if x not in s:raise ValueError('independently checked diagnostic operation absent: '+x)
 print('PASS: reference SHA-256 and exact 32 code + 4 layout bytes')
 print('PASS: independent LLVM6 assembly of all 9/9 packet words, two physical calls')
 print('PASS: Rizin V66 decode and 2816-byte reconstructed RWE prefix')

if __name__=='__main__':
 p=argparse.ArgumentParser(description=__doc__)
 for name in ('llvm-mc','rz-asm','generated','prefix','reference'):
  p.add_argument('--'+name,type=Path,required=True)
 a=p.parse_args();check(a)

"""Independently assemble remaining 316 CDSP controller descriptor bytes.

Three semantic descriptor rows are assembled with LLVM6. V66-only `SYSCFG`
read/write opcodes are replaced with nops in the *independent LLVM fixture*
and validated in generated bytes using the Rizin Hexagon decoder. All other
77 instruction words are compared exactly to a separately generated object.
"""
from __future__ import annotations
import argparse
import importlib.util
from pathlib import Path
import struct
import subprocess
import tempfile

FILE_OFFSET=0x4058
PHYS=0x96c01058
LENGTH=316
UNSUPPORTED_INDICES=(74,76)
FEATURE_ROWS=(
 (-0x1fd92b0,-0x1fd92ac,-0x1fd92a8),
 (-0x1fd92a4,-0x1fd92a0,-0x1fd929c),
 (-0x1fd9298,-0x1fd9294,-0x1fd9290),
)

def semantic_asm():
    src=['.text','.global cdsp_control_descriptor_rows','cdsp_control_descriptor_rows:']
    for group,offsets in enumerate(FEATURE_ROWS):
        src.extend(['{ r23=#170','  memw(r21+##44)=r23.new }',
                    '{ r23=#10','  memw(r21+##48)=r23.new }'])
        for n in range(2):
            src.extend([f'{{ r23=#5',f'  r22=memw(r25+##{offsets[n]})',
                        f'  if(cmp.eq(r22.new,#0)) jump:t row{group}_{n} }}',
                        '{ r23=#10 }',f'row{group}_{n}:'])
            if n==0:src.append('{ memw(r21+##0)=r23 }')
        src.extend([f'{{ r22=memw(r25+##{offsets[2]}) }}',
                    '{ r22=asl(r22,#4) }','{ r23=add(r23,r22) }',
                    '{ memw(r21+##40)=r23 }'])
        if group<2:src.append('{ r21=add(r21,#256) }')
    # LLVM6 does not know V66-only SYSCFG accesses.
    src.extend(['{ nop }','{ r21=setbit(r21,#2) }','{ nop }','{ isync }','{ jumpr lr }'])
    return '\n'.join(src)+'\n'

def module(filename,alias):
    spec=importlib.util.spec_from_file_location(alias,Path(__file__).with_name(filename))
    assert spec and spec.loader
    m=importlib.util.module_from_spec(spec);spec.loader.exec_module(m);return m

def verify(llvm:Path,rz:Path,rust_output:Path,reference:Path|None):
    got=rust_output.read_bytes()
    if len(got)!=LENGTH:raise ValueError('Controller descriptor extension must be 316 bytes')
    with tempfile.TemporaryDirectory(prefix='cdsp-remaining-control-') as d:
        asm=Path(d)/'ctrl.s';obj=Path(d)/'ctrl.o'
        asm.write_text(semantic_asm())
        subprocess.run([str(llvm),'-triple=hexagon','-mcpu=hexagonv60',
           '-filetype=obj','-o',str(obj),str(asm)],check=True)
        alt=module('verify-cdsp-hexagon-entry.py','cdsp_ctrl_elf')\
          .parse_elf32_text(obj.read_bytes())
    if len(alt)!=LENGTH:raise ValueError('LLVM controller-descriptor fixture changed size')
    rust_words=struct.unpack('<79I',got)
    llvm_words=struct.unpack('<79I',alt)
    for i,(got_word,ind_word) in enumerate(zip(rust_words,llvm_words)):
        if i not in UNSUPPORTED_INDICES and got_word!=ind_word:
            raise ValueError(f'LLVM instruction mismatch at CDSP file {FILE_OFFSET+4*i:#x}')
    decoded=module('verify-cdsp-tlb.py','cdsp_ctrl_rizin')\
      .decode_rizin(rz,got,physical_address=PHYS)
    if len(decoded)!=79 or decoded[-5:] != ['r21=syscfg','r21=setbit(r21,#0x2)',
                                           'syscfg=r21','isync','jumprlr']:
        raise ValueError('V66 controller SYSCFG epilogue not confirmed: '+repr(decoded[-5:]))
    if reference is not None:
        if reference.read_bytes()[FILE_OFFSET:FILE_OFFSET+LENGTH]!=got:
            raise ValueError('CDSP reference/controller descriptor mismatch')
    print('CDSP 316/316 exact bytes: 77 LLVM-independent instruction words, two Rizin-confirmed privileged SYSCFG words, all 79 decoded')

def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--llvm-mc',type=Path,required=True)
    p.add_argument('--rz-asm',type=Path,required=True)
    p.add_argument('--rust-output',type=Path,required=True)
    p.add_argument('--reference',type=Path)
    a=p.parse_args();verify(a.llvm_mc,a.rz_asm,a.rust_output,a.reference)
if __name__=='__main__':main()

"""Independent LLVM6/Rizin checks for the 64-byte CDSP V66 registry cleaner.

LLVM6 is semantically equivalent but shortens two GP-based loads and inserts
one zero-extender. Exact original parse-marker/branch-target bytes are verified
by Rizin V66 and strict comparison against the private CDSP MBN.
"""
import argparse
import importlib.util
import re
import subprocess
import tempfile
from pathlib import Path

OFFSET=0x561a0
LENGTH=64
PHYSICAL=0x96cc81a0


def source_text_from_llvm(binary:bytes)->bytes:
    spec=importlib.util.spec_from_file_location('cdsp_elf_parser',Path(__file__).with_name('verify-cdsp-hexagon-entry.py'))
    if not spec or not spec.loader:
        raise RuntimeError('Cannot load ELF section parser')
    module=importlib.util.module_from_spec(spec);spec.loader.exec_module(module)
    return module.parse_elf32_text(binary)


def verify(llvm_mc:Path,rz_asm:Path,generated:Path,reference:Path|None):
    content=generated.read_bytes()
    if len(content)!=LENGTH:
        raise ValueError(f'expected {LENGTH} independently generated bytes, got {len(content)}')
    with tempfile.TemporaryDirectory(prefix='cdsp-rwe-registry-') as directory:
        obj=Path(directory)/'semantic.o'
        subprocess.run([str(llvm_mc),'-triple=hexagon','-mcpu=hexagonv60',
                        '-filetype=obj',str(Path(__file__).with_name('late-rwe-registry.s')),
                        '-o',str(obj)],check=True)
        llvm=source_text_from_llvm(obj.read_bytes())[0x1a0:]
    if len(llvm)!=60:
        raise ValueError(f'LLVM6 semantically equivalent output should be 60, got {len(llvm)} bytes')
    u32=lambda b:[int.from_bytes(b[x:x+4],'little') for x in range(0,len(b),4)]
    llvm_words=u32(llvm)
    reference_words=u32(content)
    for i,j in {2:1,3:2,4:3,5:4,6:5,7:6,11:9,12:10,13:12,14:13,15:14}.items():
        if reference_words[i]!=llvm_words[j]:
            raise ValueError(f'LLVM6 independent equivalence differs for word {i} (LLVM word {j})')
    # Two GP loads use original V66 two-word extended forms, while LLVM6
    # shortens them. LLVM's second-new branch has a shorter displacement
    # because that packet starts one instruction earlier. LLVM also puts a
    # zero extender before the final R2.new store that original omits.
    if llvm_words[0]!=0x4d877002 or llvm_words[7]!=0x499840a2 or \
            llvm_words[8]!=0x2402c008 or llvm_words[11]!=0x00004000:
        raise ValueError('unexpected LLVM6 compact GP/.new emitter selection')
    rz=subprocess.run([str(rz_asm),'-a','hexagon','-b','32','-o',hex(PHYSICAL),
                       '-D',content.hex()],capture_output=True,text=True,check=True)
    lines=[l for l in rz.stdout.splitlines() if l.startswith('0x')]
    if len(lines)!=16 or any('invalid' in l.lower() for l in lines):
        raise ValueError(f'Rizin failed to decode all 16 words: {len(lines)} decoded')
    decoded='\n'.join(lines).lower().replace(' ','')
    for expected in [
        'memw(gp+##0xc0363e00)','allocframe(sp,#0x8)',
        'jump:nt0x96cc81dc','memd(sp+##0x0)=r17:16',
        'memw(r16=##0xc028c024)','memw(gp+##0xc028c014)',
        'jump:nt0x96cc81d4','r1:0=combine(##0x4,r16)',
        'callrr2','memw(r16+##0x0)=r2.new','dealloc_return',
    ]:
        if expected not in decoded:
            raise ValueError('Missing V66 operation in original packet order: '+expected)
    if reference is not None and reference.read_bytes()[OFFSET:OFFSET+LENGTH]!=content:
        raise ValueError('source-built CDSP callback registry bytes differ from private firmware')
    print('PASS 64 Hexagon source-derived bytes: LLVM6 confirms 11 identical words and equivalent instructions for 5 differing forms; Rizin V66 decodes all 16 original packet words; original reference matches.')

if __name__=='__main__':
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--llvm-mc',type=Path,required=True)
    p.add_argument('--rz-asm',type=Path,required=True)
    p.add_argument('--generated',type=Path,required=True)
    p.add_argument('--reference',type=Path)
    x=p.parse_args();verify(x.llvm_mc,x.rz_asm,x.generated,x.reference)

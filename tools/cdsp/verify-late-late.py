"""Independent Hexagon v60 assembly and V66 decoder audit of late CDSP MMIO.

Only compares a separately authored instruction fixture with the generated
Rust fragment. The OEM reference is accepted for final byte comparison, never
embedded into any Rust or assembly source.
"""
from __future__ import annotations
import argparse, importlib.util, os, re, subprocess, tempfile
from pathlib import Path

FILE_OFFSET=0x55000
PHYSICAL_ADDRESS=0x96cc7000
EXPECTED_CODE_LEN=0x38
JOINED_CODE_LEN=0x70

def fixture(joined:bool=False)->str:
    lines=['.text','.global cdsp_late_mmio_init','cdsp_late_mmio_init:']
    for address in (0x083a0040,0x083a0044,0x083a0048):
        lines.extend((f'{{ r0 = ##{address} }}', '{ memw(r0+#0) = ##7 }'))
    lines.extend(('{ barrier }', '{ jump cdsp_late_shared }'))
    if joined:
        lines.extend((
            '{ r8=r1; r9=r2; r10=r3 }',
            '{ r2=r0 }',
            '{ r0=##0x083a2000 }',
            '{ r1=memw(r0+#0) }',
            'again:',
            '{ r3=memw(r0+#0) }',
            '{ r3=sub(r3,r1) }',
            '{ p0=cmp.gtu(r3,r2); if (!p0.new) jump:t again }',
            '{ r1=r8; r2=r9; r3=r10 }',
            '{ jumpr r13 }',
        ))
    else:
        lines.append('.space 0x38')  # PC-relative target, NOT independently reconstructed bytes.
    lines.append('cdsp_late_shared:')
    return '\n'.join(lines)+'\n'

def llvm_text(obj:bytes)->bytes:
    helper=Path(__file__).with_name('verify-cdsp-hexagon-entry.py')
    spec=importlib.util.spec_from_file_location('cdsp_audit_llvm_parser',helper)
    if spec is None or spec.loader is None: raise RuntimeError('CDSP existing ELF parser unavailable')
    module=importlib.util.module_from_spec(spec);spec.loader.exec_module(module)
    return module.parse_elf32_text(obj)

def verify(llvm:Path,rz:Path,generated:Path,reference:Path|None,joined:bool=False)->None:
    rebuilt=generated.read_bytes()
    expected_len=JOINED_CODE_LEN if joined else EXPECTED_CODE_LEN
    if len(rebuilt)!=expected_len:raise ValueError(f'Expected {expected_len} generated bytes, got {len(rebuilt)}')
    with tempfile.TemporaryDirectory(prefix='agent20-10-cdsp-') as work:
        src=Path(work)/'late-init.s';obj=Path(work)/'late-init.o';src.write_text(fixture(joined))
        subprocess.run([str(llvm),'-triple=hexagon','-mcpu=hexagonv60','-filetype=obj','-o',str(obj),str(src)],check=True)
        alt=llvm_text(obj.read_bytes())
    if alt[:expected_len]!=rebuilt:
        offset=next(i for i,(x,y) in enumerate(zip(alt,rebuilt)) if x!=y)
        raise ValueError(f'Independent LLVM6 mismatch at CDSP file offset {FILE_OFFSET+offset:#x}')
    # V66 disassembly makes packet-marker and immediate semantics explicit.
    env=os.environ.copy()
    # Caller can pass a staged-runtime LD_LIBRARY_PATH for Rizin if required.
    dec=subprocess.run([str(rz),'-a','hexagon','-b','32','-o',hex(PHYSICAL_ADDRESS),'-D',rebuilt.hex()],
                       capture_output=True,text=True,env=env,check=True)
    lines=[x for x in dec.stdout.splitlines() if x.startswith('0x')]
    if len(lines)!=expected_len//4:raise ValueError(f'Rizin expected {expected_len//4} Hexagon instruction words, got {len(lines)}')
    expected=['immext', 'r0 = ##0x83a0040','immext','memw(r0+#0x0) = ##0x7',
              'immext','r0 = ##0x83a0044','immext','memw(r0+#0x0) = ##0x7',
              'immext','r0 = ##0x83a0048','immext','memw(r0+#0x0) = ##0x7',
              'barrier','jump 0x96cc7070']
    if joined:
        expected.extend([
            'r8 = r1', 'r9 = r2', 'r10 = r3', 'r2 = r0', 'immext',
            'r0 = ##0x83a2000', 'r1 = memw(r0+##0x0)',
            'r3 = memw(r0+##0x0)', 'r3 = sub(r3,r1)',
            'p0 = cmp.gtu(r3,r2); if (!p0.new) jump:t 0x96cc7054',
            'r1 = r8','r2 = r9','r3 = r10','jumpr r13',
        ])
    for i,(line,want) in enumerate(zip(lines,expected)):
        norm=' '.join(line.split()[4:]).lower().replace(' ', '')
        if want.replace(' ','') not in norm:
            raise ValueError(f'Rizin decoded unexpected word {i}, {line!r}, wanted {want!r}')
    if reference is not None:
        original=reference.read_bytes()
        if original[FILE_OFFSET:FILE_OFFSET+expected_len]!=rebuilt:
            raise ValueError('The emitted late CDSP MMIO code differs from the original image')
    print(f'OK: {expected_len}/{expected_len} source-generated CDSP executable bytes; {expected_len//4} Hexagon instruction words,')
    print('    LLVM6-assembled semantic packets, Rizin V66 instruction/marker checks, exact OEM comparison')

def main():
    ap=argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--llvm-mc',type=Path,required=True);ap.add_argument('--rz-asm',type=Path,required=True)
    ap.add_argument('--generated',type=Path,required=True);ap.add_argument('--reference',type=Path)
    ap.add_argument('--joined',action='store_true',help='Independently verify full 112-byte entry plus wait loop')
    args=ap.parse_args()
    verify(args.llvm_mc,args.rz_asm,args.generated,args.reference,args.joined)
if __name__=='__main__':main()

"""Compare independently authored LLVM6 prologue with checked V66 Rust output."""
import argparse,hashlib,importlib.util,re,subprocess,tempfile
from pathlib import Path
START,END=0x568f0,0x56930
PIN='febeae7b8e47bad4eeabc159a3c24b74cda26dfa12b384c31de5de30817e06ea'

def verify(a):
    f=a.reference.read_bytes()
    if hashlib.sha256(f).hexdigest()!=PIN:raise ValueError('Wrong CDSP original SHA-256')
    code=a.generated.read_bytes()
    joined=a.prefix.read_bytes()
    if len(code)!=64 or code!=f[START:END]:raise ValueError('64 generated bytes differ from OEM pinned bytes')
    if len(joined)!=END-0x56000 or joined!=f[0x56000:END]:raise ValueError('2352-byte RWE prefix not byte-identical')
    spec=importlib.util.spec_from_file_location('hexagon_elf',Path(__file__).with_name('verify-cdsp-hexagon-entry.py'))
    assert spec and spec.loader
    mod=importlib.util.module_from_spec(spec);spec.loader.exec_module(mod)
    with tempfile.TemporaryDirectory(prefix='cdsp-frame-') as td:
        files=[]
        for name in ('late-controller-frame-setup.s','late-controller-frame-duplex.s'):
            obj=Path(td)/(name+'.o')
            subprocess.run([str(a.llvm_mc),'-triple=hexagon','-mcpu=hexagonv60','-filetype=obj',
                          str(Path(__file__).with_name(name)),'-o',str(obj)],check=True,capture_output=True,text=True)
            files.append((obj,mod.parse_elf32_text(obj.read_bytes())))
        alt=files[0][1][0x8f0:0x930]
        semantic_ops=subprocess.run([str(a.llvm_objdump),'-d',str(files[0][0])],check=True,capture_output=True,text=True).stdout
        packet_asm=files[1][1]
    if len(alt)!=64:raise ValueError('LLVM standalone prologue length is wrong')
    same=sum(alt[i:i+4]==code[i:i+4] for i in range(0,64,4))
    if same!=13 or alt[12:]!=code[12:]:raise ValueError(f'Expected 13 same LLVM6 packet words, observed {same}')
    if packet_asm[:4]!=code[:4] or packet_asm[8:12]!=code[8:12]:
        raise ValueError('LLVM separately assembled extended assignment or duplex differs')
    if not all(s in semantic_ops for s in ('memd(r29+#80)','memd(r29+#88)','memd(r29+#32)','allocframe(#96)')):
        raise ValueError('LLVM6 does not decode the original frame store semantics')
    print('PASS 64 exact independently source-generated executable bytes; joined RWE 2352 = 2296 executable + 56 NOP/layout')
    print('PASS LLVM6 prologue: 13/16 words directly identical, original allocation duplex separately assembled identically')
    print('PASS LLVM6 verified 4 explicit codec FourCC pointers, frame stack saves and 96-byte allocation')

if __name__=='__main__':
    p=argparse.ArgumentParser()
    for n in ('llvm-mc','llvm-objdump','generated','prefix','reference'):p.add_argument('--'+n,required=True,type=Path)
    verify(p.parse_args())

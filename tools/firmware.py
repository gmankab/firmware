"""Unified, fail-closed Xiaomi Nabu firmware source/verification CLI."""
from __future__ import annotations
import argparse
import json
from pathlib import Path
import subprocess
import sys

if __package__ in (None, ""):
    sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from tools.build.firmware_coverage import (DEFAULT_MANIFEST,PROJECT_ROOT,CoverageError,
    holes,image_for,load,status,verify_generated_region,verify_reference)


def main(argv: list[str] | None = None) -> int:
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--manifest",type=Path,default=DEFAULT_MANIFEST)
    sub=parser.add_subparsers(dest="action",required=True)
    sub.add_parser("images",help="list available pinned source images")
    cov=sub.add_parser("coverage",help="report source/layout byte claims and executable holes")
    cov.add_argument("image",nargs="?");cov.add_argument("--json",action="store_true")
    vr=sub.add_parser("verify-reference",help="strict reference size and SHA-256 match")
    vr.add_argument("image");vr.add_argument("reference",type=Path)
    cmp=sub.add_parser("compare",help="compare generated bytes to one file offset of pinned original")
    cmp.add_argument("image");cmp.add_argument("reference",type=Path);cmp.add_argument("generated",type=Path)
    cmp.add_argument("--offset",type=lambda x:int(x,0),required=True)
    st=sub.add_parser("status",help="print or check generated status documentation")
    st.add_argument("--check",action="store_true");st.add_argument("--write",action="store_true")
    build=sub.add_parser("build",help="build only a fully independent supported reference file")
    build.add_argument("image");build.add_argument("--output",type=Path,required=True)
    build.add_argument("--firmware-tools",default="firmware-tools",help="path to the existing Rust CLI binary")
    args=parser.parse_args(argv)
    try:
        ledger=load(args.manifest)
        if args.action=="images":
            for item in ledger["images"]:print(item["name"])
        elif args.action=="coverage":
            images=[image_for(ledger,args.image)] if args.image else ledger["images"]
            summary=[]
            for i in images:
                record={"image":i["name"],"original_bytes":i["size"],"reported_generated_or_modelled_bytes":i["credit_bytes"],"not_credited_bytes":i["size"]-i["credit_bytes"],"credit_kind":i["credit_kind"]}
                if "executable_load" in i:
                    record["uncovered_executable_intervals"]=holes(i.get("regions",[]),0,i["executable_load"]["runtime_end"])
                summary.append(record)
            if args.json:print(json.dumps(summary,indent=2))
            else:
                for i in summary:print(f"{i['image']}: {i['reported_generated_or_modelled_bytes']:,}/{i['original_bytes']:,} generated/modelled; {i['not_credited_bytes']:,} not credited")
                if args.image and "uncovered_executable_intervals" in summary[0]:
                    for gap in summary[0]["uncovered_executable_intervals"]:print(f"  hole 0x{gap['start']:x}–0x{gap['end']:x}: {gap['bytes']:,} bytes")
        elif args.action=="verify-reference":print(json.dumps(verify_reference(ledger,args.image,args.reference),indent=2))
        elif args.action=="compare":print(json.dumps(verify_generated_region(ledger,args.image,args.reference,args.generated,args.offset),indent=2))
        elif args.action=="status":
            output=status(ledger)
            status_path=PROJECT_ROOT/"docs/STATUS.md"
            if args.check:
                if not status_path.exists() or status_path.read_text()!=output:
                    raise CoverageError(f"{status_path} is stale: run `python3 -m tools.firmware status --write`")
                print("firmware status document matches pinned coverage manifest")
            elif args.write:status_path.write_text(output);print(f"updated {status_path}")
            else:print(output,end="")
        elif args.action=="build":
            image=image_for(ledger,args.image)
            if not image.get("complete_source",False):
                raise CoverageError(f"{args.image}: full independent source build unavailable; refusing to substitute original bytes")
            if args.image!="modemuw.jsn":
                raise CoverageError(f"{args.image}: complete-source builder not implemented")
            args.output.parent.mkdir(parents=True,exist_ok=True)
            subprocess.run([args.firmware_tools,"rebuild-modemuw",str(args.output)],check=True)
        return 0
    except (CoverageError,OSError,subprocess.CalledProcessError) as e:
        print(f"firmware: {e}",file=sys.stderr)
        return 2


if __name__=="__main__":
    # Allow standalone execution from anywhere as well as `python3 -m tools.firmware`.
    raise SystemExit(main())

"""Audit observed DLM zero-bank copy dependencies across two pinned revisions.

This verifies *reference-assisted* relationships only; it does not claim the
unknown original buffer initialization semantics nor source-generated bytes.
"""
from __future__ import annotations
import argparse, hashlib, json
from pathlib import Path

KNOWN_SHA256={
 '8b845514621ebfd95759a0919f3aa3d825314abb478a7cad1c3fb4c6872b70b5':'postmarketOS',
 '72364eca0a91855d59e043371aca774354e5ad0885df5024edcec8f976543ad2':'map220v',
}
ALIASES=((0x2271c,336),(0x22875,395),(0x262ec,1812))
BANK_DELTA=0x4000
TOTAL_BYTES=2543
assert sum(n for _,n in ALIASES)==TOTAL_BYTES


def check_spans(image: bytes, require_zero: bool=False) -> dict:
    matched=0
    for start,length in ALIASES:
        if start+length+BANK_DELTA>len(image):
            raise ValueError(f'truncated DLM bank alias at file 0x{start:x}')
        lower=image[start:start+length]
        upper=image[start+BANK_DELTA:start+BANK_DELTA+length]
        if lower != upper:
            at=next(i for i,(x,y) in enumerate(zip(lower,upper)) if x!=y)
            raise ValueError(f'DLM bank copy differs at file 0x{start+BANK_DELTA+at:x}')
        if require_zero and any(lower):
            raise ValueError(f'known original zero-span contains nonzero values at 0x{start:x}')
        matched+=length
    assert matched==TOTAL_BYTES
    return dict(copied_bytes=matched,dependent_bytes=matched,independent_source_bytes_added=0,
                spans=len(ALIASES),source_inputs_required=True)


def verify_pinned(image: bytes) -> dict:
    digest=hashlib.sha256(image).hexdigest()
    if len(image)!=196608 or digest not in KNOWN_SHA256:
        raise ValueError('input is not either pinned Novatek firmware revision')
    return dict(schema='agent20-19-dlm-zero-aliases-v1',revision=KNOWN_SHA256[digest],
                sha256=digest,**check_spans(image, require_zero=True))


def main() -> None:
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('firmware',type=Path)
    a=p.parse_args()
    print(json.dumps(verify_pinned(a.firmware.read_bytes()),indent=2))

if __name__=='__main__':main()

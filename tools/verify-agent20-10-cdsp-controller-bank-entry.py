"""Independently cross-check the first 48 Hexagon V66 bank enumerator bytes.

An original packet continues beyond this fragment: LLVM 6 terminates the
last LSR as a singleton packet. The only accepted difference is the parse
marker (bits 14..15) on the final word. Actual reference and generated bytes
must match all 48 bytes, including that marker.
"""
import argparse,hashlib,importlib.util,os,subprocess,tempfile,struct
from pathlib import Path
START=0x56b00;END=0x56b30;RWE=0x56000
SHA='febeae7b8e47bad4eeabc159a3c24b74cda26dfa12b384c31de5de30817e06ea'

def parse_text(b):
 p=Path(__file__).with_name('verify-cdsp-hexagon-entry.py')
 spec=importlib.util.spec_from_file_location('hexagon_audit_entry',p)
 if not spec or not spec.loader:raise RuntimeError('missing independent ELF32 text parser')
 mod=importlib.util.module_from_spec(spec);spec.loader.exec_module(mod)
 return mod.parse_elf32_text(b)

def main():
 a=argparse.ArgumentParser(description=__doc__)
 for n in ('llvm-mc','rz-asm','generated','prefix','reference'):
  a.add_argument('--'+n,required=True,type=Path)
 arg=a.parse_args()
 ref=arg.reference.read_bytes();gen=arg.generated.read_bytes();prefix=arg.prefix.read_bytes()
 if hashlib.sha256(ref).hexdigest()!=SHA:raise ValueError('reference revision SHA256 mismatch')
 if len(gen)!=END-START or gen!=ref[START:END]:raise ValueError('typed 48-byte bank prologue mismatches CDSP')
 if len(prefix)!=END-RWE or prefix!=ref[RWE:END]:raise ValueError('joined RWE prefix mismatches original bytes')
 with tempfile.TemporaryDirectory(prefix='cdsp-bank48-') as folder:
  obj=Path(folder)/'independent.o'
  subprocess.run([str(arg.llvm_mc),'-triple=hexagon','-mcpu=hexagonv60',
     '-filetype=obj',str(Path(__file__).with_name('agent20-10-cdsp-controller-bank-entry.s')),
     '-o',str(obj)],capture_output=True,text=True,check=True)
  llvm=parse_text(obj.read_bytes())[0xb00:0xb30]
 if len(llvm)!=len(gen):raise ValueError('LLVM6 did not assemble exactly 12 words')
 differences=[i for i,(x,y) in enumerate(zip(llvm,gen)) if x!=y]
 if differences and differences!=[45]:
  raise ValueError(f'additional LLVM6 differences beyond final packet marker: {differences}')
 orig_last,llvm_last=struct.unpack_from('<I',gen,44)[0],struct.unpack_from('<I',llvm,44)[0]
 if (orig_last&~0xc000)!=(llvm_last&~0xc000):raise ValueError('final LSR operand differs from LLVM6')
 env=os.environ.copy()
 lib=next((p/'ubuntu-runtime/build-deps-flat' for p in arg.rz_asm.resolve().parents
     if (p/'ubuntu-runtime/build-deps-flat').is_dir()),None)
 if lib:env['LD_LIBRARY_PATH']=str(lib)+':'+env.get('LD_LIBRARY_PATH','')
 rez=subprocess.run([str(arg.rz_asm),'-a','hexagon','-b','32','-o','0x96cc8b00','-D',gen.hex()],
         env=env,text=True,capture_output=True,check=True).stdout
 lines=[x for x in rez.splitlines() if x.startswith('0x')]
 if len(lines)!=12 or 'invalid' in rez.lower():raise ValueError('Rizin did not parse exactly 12 valid V66 words')
 if 'jump:nt 0x96cc8e1c' not in lines[9]:raise ValueError('controller missing-resource branch target differs')
 if 'lsr(R2,#0xc)' not in lines[11]:raise ValueError('final LSR operand differs')
 print('VERIFY: 48 Rust-emitted bytes exactly match pinned CDSP; joined RWE prefix 2864 bytes exact')
 print('LLVM6: 11/12 words exactly match; last LSR differs only in continuation marker')
 print('Rizin V66: 12/12 original words valid, branch target/packet continuation confirmed')
if __name__=='__main__':main()

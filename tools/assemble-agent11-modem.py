"""Assemble independently authored Hexagon V60 early modem handlers.

No OEM instruction bytes are embedded. LLVM6 emits register/packet opcodes;
privileged S-register forms are generated by checked public-ISA macros.
The reference MBN is an optional private, SHA-pinned verification input only.
"""
from __future__ import annotations
import argparse
import hashlib
from pathlib import Path
import runpy
import subprocess
import sys
import tempfile

FILE_START=0x4058
PHYSICAL_START=0x8e001058
ELF_VADDR=0xc0801058
EXPECTED_SHA256="6f5cb32bc10e41abb40938d185805e788f5637a41d3ebcef278e4e169fc36782"


def text_from_object(data:bytes)->bytes:
    # Reuse the ELF32 section parser already covered by prior Agent 06 tests.
    path=Path(__file__).with_name("assemble-modem-tlb.py")
    return runpy.run_path(str(path))["text_from_object"](data)


def assemble(llvm_mc:Path,source:Path)->bytes:
    with tempfile.TemporaryDirectory(prefix="nabu-agent11-hexagon-") as td:
        obj=Path(td)/"source.o"
        cmd=[str(llvm_mc),"-triple=hexagon","-mcpu=hexagonv60","-filetype=obj",str(source),"-o",str(obj)]
        result=subprocess.run(cmd,capture_output=True,text=True,check=False)
        if result.returncode:
            raise ValueError("Hexagon V60 source assembly failed: "+result.stderr.strip())
        encoded=text_from_object(obj.read_bytes())
    if len(encoded)%4:
        raise ValueError("Hexagon emission does not end on a 32-bit instruction boundary")
    if not encoded:
        raise ValueError("empty assembled Hexagon text is not a verified fragment")
    return encoded


def verify_reference(reference:bytes,generated:bytes,start:int=FILE_START)->None:
    digest=hashlib.sha256(reference).hexdigest()
    if digest!=EXPECTED_SHA256:
        raise ValueError(f"incorrect revision of modem.mbn: {digest}")
    end=start+len(generated)
    expected=reference[start:end]
    if len(expected)!=len(generated):
        raise ValueError(f"truncated reference before file offset {end:#x}")
    if generated!=expected:
        mismatches=[i for i,(a,b) in enumerate(zip(expected,generated)) if a!=b]
        i=mismatches[0]
        raise ValueError(f"modem byte difference at file {start+i:#x}: reference={expected[i]:#04x}, generated={generated[i]:#04x}")


def main()->int:
    parser=argparse.ArgumentParser(description=__doc__)
    root=Path(__file__).resolve().parents[1]
    parser.add_argument("--llvm-mc",required=True,type=Path)
    parser.add_argument("--source",type=Path,default=root/"crates/firmware-tools/src/devices/xiaomi_nabu/modem_entry_followup.s")
    parser.add_argument("--output",required=True,type=Path)
    parser.add_argument("--reference",type=Path,help="private unchanged modem.mbn revision for byte equality")
    args=parser.parse_args()
    try:
        code=assemble(args.llvm_mc,args.source)
        if args.reference:verify_reference(args.reference.read_bytes(),code)
        args.output.write_bytes(code)
        print(f"Emitted {len(code)} source-generated Hexagon bytes, modem file [{FILE_START:#x},{FILE_START+len(code):#x}), physical [{PHYSICAL_START:#x},{PHYSICAL_START+len(code):#x}); SHA256 {hashlib.sha256(code).hexdigest()}")
        if args.reference:print("Reference bytes match exactly (same pinned source revision)")
        print("Partial reconstruction only, not an authenticated or flashable MBN")
        return 0
    except (ValueError,OSError) as exc:
        print("ERROR:",exc,file=sys.stderr)
        return 1

if __name__=="__main__":sys.exit(main())

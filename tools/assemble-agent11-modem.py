"""Assemble independently authored Hexagon V60 early modem handlers.

No OEM instruction bytes are embedded. LLVM6 emits register/packet opcodes;
privileged S-register forms are generated by checked public-ISA macros.
The reference MBN is an optional private, SHA-pinned verification input only.
"""
from __future__ import annotations
import argparse
import hashlib
import struct
from pathlib import Path
import runpy
import subprocess
import sys
import tempfile

FILE_START=0x4058
PHYSICAL_START=0x8e001058
ELF_VADDR=0xc0801058
EXPECTED_SHA256="6f5cb32bc10e41abb40938d185805e788f5637a41d3ebcef278e4e169fc36782"


def text_from_object(data:bytes)->bytes:
    # Reuse the ELF32 section parser already covered by prior Agent 06 tests.
    path=Path(__file__).with_name("assemble-modem-tlb.py")
    return runpy.run_path(str(path))["text_from_object"](data)


def restore_original_legal_hexagon_packet_order(code: bytes) -> bytes:
    """Restore predicated-branch packet order, preserving ISA operand bits.

    LLVM 6's Hexagon packet scheduler canonicalizes one legal 3-word packet
    into branch, extender, predicate instead of original extender, predicate,
    branch. Re-order *only* those LLVM-authored instructions after checking
    their operation classes and parse-marker fields. This is not an OEM
    byte-array splice; all words came from original LLVM source assembly.
    """
    rel=0x42bc-FILE_START
    if len(code)<rel+12:return code
    branch,extension,comparison=struct.unpack_from('<III',code,rel)
    marker=0b11<<14
    if ((branch&0xff000000)!=0x5c000000 or
        (branch&marker)!=(1<<14) or
        (extension&0xf0000000)!=0x00000000 or
        (extension&marker)!=(1<<14) or
        (comparison&0xff000000)!=0x75000000 or
        ((comparison>>16)&0x1f)!=2 or
        (comparison&marker)!=(3<<14)):
        raise ValueError('unexpected Hexagon LLVM6 scheduling at file 0x42bc; refuse to alter')
    comparison=(comparison&~marker)|(1<<14)
    branch=(branch&~marker)|(3<<14)
    out=bytearray(code)
    struct.pack_into('<III',out,rel,extension,comparison,branch)
    # LLVM6 also canonicalizes the compact compare-and-branch packet at
    # 0x4578 from branch/predicate to predicate/branch. Both orderings are
    # legal on Hexagon, but the source-reference packet's parse bits differ.
    rel2=0x4578-FILE_START
    if len(out)>=rel2+8:
        branch2,comparison2=struct.unpack_from('<II',out,rel2)
        if ((branch2&0xff000000)!=0x5c000000 or
            (branch2&marker)!=(1<<14) or
            (comparison2&0xff000000)!=0x75000000 or
            ((comparison2>>16)&0x1f)!=25 or
            (comparison2&marker)!=(3<<14)):
            raise ValueError('unexpected Hexagon compact predicate packet at 0x4578')
        comparison2=(comparison2&~marker)|(1<<14)
        branch2=(branch2&~marker)|(3<<14)
        struct.pack_into('<II',out,rel2,comparison2,branch2)
    # LLVM6 also emits the valid increment-and-loop-back packet at 0x45fc
    # as branch/increment; retain the OEM source packet's increment/branch
    # ordering without changing any branch displacement or operand fields.
    rel3=0x45fc-FILE_START
    if len(out)>=rel3+8:
        branch3,increment=struct.unpack_from('<II',out,rel3)
        if ((branch3&0xff000000)!=0x59000000 or
            (branch3&marker)!=(1<<14) or
            (increment&0xff000000)!=0xb0000000 or
            (increment&marker)!=(3<<14)):
            raise ValueError('unexpected Hexagon increment/branch packet at 0x45fc')
        increment=(increment&~marker)|(1<<14)
        branch3=(branch3&~marker)|(3<<14)
        struct.pack_into('<II',out,rel3,increment,branch3)
    # At modem 0x4674 the independent assembler swaps the .new comparison
    # and branch within one legal two-instruction packet. Restore the OEM
    # source packet order, with checked classes and parse bit transitions.
    rel4=0x4674-FILE_START
    if len(out)>=rel4+8:
        branch4,compare4=struct.unpack_from('<II',out,rel4)
        if ((branch4&0xff000000)!=0x5c000000 or
            (branch4&marker)!=(1<<14) or
            (compare4&0xff000000)!=0x75000000 or
            ((compare4>>16)&0x1f)!=2 or
            (compare4&marker)!=(3<<14)):
            raise ValueError('unexpected Hexagon comparator/branch packet at 0x4674')
        compare4=(compare4&~marker)|(1<<14)
        branch4=(branch4&~marker)|(3<<14)
        struct.pack_into('<II',out,rel4,compare4,branch4)
    # LLVM6 similarly schedules a four-word absolute-pointer / new-predicate
    # packet as branch/extender/address/comparison. The original legal packet
    # orders extender/address/comparison/branch. Preserve only ISA fields.
    rel5=0x46f4-FILE_START
    if len(out)>=rel5+16:
        branch5,extender5,address5,compare5=struct.unpack_from('<IIII',out,rel5)
        if ((branch5&0xff000000)!=0x5c000000 or
            (branch5&marker)!=(1<<14) or
            (extender5&0xf0000000)!=0 or
            (extender5&marker)!=(1<<14) or
            (address5&0xff000000)!=0xb0000000 or
            ((address5>>16)&31)!=25 or
            (address5&marker)!=(1<<14) or
            (compare5&0xff000000)!=0x75000000 or
            ((compare5>>16)&31)!=3 or
            (compare5&marker)!=(3<<14)):
            raise ValueError('unexpected Hexagon 4-word branch packet at 0x46f4')
        compare5=(compare5&~marker)|(1<<14)
        branch5=(branch5&~marker)|(3<<14)
        struct.pack_into('<IIII',out,rel5,extender5,address5,compare5,branch5)
    # Indexed pagewalk: packet-local conditional count compare and its
    # backedge branch are legal in either LLVM6 order. The original places
    # the compare first. Preserve exclusively source-authored operand bits.
    rel6=0x47c4-FILE_START
    if len(out)>=rel6+8:
        branch6,compare6=struct.unpack_from('<II',out,rel6)
        if ((branch6&0xff000000)!=0x5c000000 or
            (branch6&marker)!=(1<<14) or
            (compare6&0xff000000)!=0xf2000000 or
            (compare6&0x001f0000)!=0x00080000 or
            (compare6&marker)!=(3<<14)):
            raise ValueError('unexpected Hexagon pagewalk count/backedge packet at 0x47c4')
        compare6=(compare6&~marker)|(1<<14)
        branch6=(branch6&~marker)|(3<<14)
        struct.pack_into('<II',out,rel6,compare6,branch6)
    # Two compact `.new` compare/branch packets in the protected cache and
    # physical-copy helpers. LLVM 6 writes branch,compare; the source firmware
    # packet has compare,branch. Reconstruct the packet without copying bytes.
    for location, tested_register, compare_marker, branch_marker in (
        (0x4814,2,3,3),  # the comparison is initially END
        (0x4870,3,1,1),  # a four-word packet continues through the memory load
    ):
        rel7=location-FILE_START
        if len(out)>=rel7+8:
            branch7,compare7=struct.unpack_from('<II',out,rel7)
            if ((branch7&0xff000000)!=0x5c000000 or
                (branch7&marker)!=(1<<14) or
                (compare7&0xff000000)!=0x75000000 or
                ((compare7>>16)&31)!=tested_register or
                (compare7&marker)!=(compare_marker<<14)):
                raise ValueError(f'unexpected compact Hexagon compare/branch packet at {location:#x}')
            compare7=(compare7&~marker)|(1<<14)
            branch7=(branch7&~marker)|(branch_marker<<14)
            struct.pack_into('<II',out,rel7,compare7,branch7)
    # Protected S27 halfword publication groups the r1 shift with the
    # extended zero register initialization and physical-memory load. LLVM6
    # seals the one-instruction shift packet early; only its parse marker is
    # repaired, after checking the independently assembled instruction class.
    rel8=0x4938-FILE_START
    if len(out)>=rel8+4:
        shift=struct.unpack_from('<I',out,rel8)[0]
        if ((shift&0xff000000)!=0x8c000000 or
            ((shift>>16)&31)!=1 or
            (shift&marker)!=(3<<14)):
            raise ValueError('unexpected Hexagon S27 shift packet at file 0x4938')
        struct.pack_into('<I',out,rel8,(shift&~marker)|(1<<14))
    # Exception handler compares an extended magic device word against 37.
    # LLVM6 legally orders its conditional branch before the extender and
    # comparison; preserve OEM packet ordering after strict class checking.
    rel9=0x4a30-FILE_START
    if len(out)>=rel9+12:
        branch9,ext9,cmp9=struct.unpack_from('<III',out,rel9)
        if ((branch9&0xff000000)!=0x5c000000 or
            (branch9&marker)!=(1<<14) or
            (ext9&0xf0000000)!=0 or
            (ext9&marker)!=(1<<14) or
            (cmp9&0xff000000)!=0x75000000 or
            ((cmp9>>16)&31)!=0 or
            (cmp9&marker)!=(3<<14)):
            raise ValueError('unexpected Hexagon 3-word exception predicate packet at 0x4a30')
        cmp9=(cmp9&~marker)|(1<<14)
        branch9=(branch9&~marker)|(3<<14)
        struct.pack_into('<III',out,rel9,ext9,cmp9,branch9)
    # The protected exception continuation checks controller R24 and
    # branches on its new predicate within one two-word packet. LLVM6 moves
    # the branch before the comparison, another architecturally valid order;
    # keep the original compare-first ordering with strict ISA-class checks.
    rel10=0x4d88-FILE_START
    if len(out)>=rel10+8:
        branch10,comparison10=struct.unpack_from('<II',out,rel10)
        if ((branch10&0xff000000)!=0x5c000000 or
            (branch10&marker)!=(1<<14) or
            (comparison10&0xff000000)!=0x75000000 or
            ((comparison10>>16)&31)!=24 or
            (comparison10&marker)!=(3<<14)):
            raise ValueError('unexpected Hexagon exception-controller compare/branch packet at 0x4d88')
        comparison10=(comparison10&~marker)|(1<<14)
        branch10=(branch10&~marker)|(3<<14)
        struct.pack_into('<II',out,rel10,comparison10,branch10)
    # Hexagon combines the R4 decrement with a predicate-and-loop branch.
    # LLVM6 hoists the predicate/branch ahead of the decrement, while the
    # original legal packet has the decrement first and its compact branch
    # last. Reorder only after checking register and ISA operation classes.
    rel11=0x4db8-FILE_START
    if len(out)>=rel11+8:
        branch11,decrement11=struct.unpack_from('<II',out,rel11)
        if ((branch11&0xffff3fff)!=0x10440008 or
            (branch11&marker)!=(1<<14) or
            (decrement11&0xffff3fff)!=0xbfe43fe4 or
            (decrement11&marker)!=(3<<14)):
            raise ValueError('unexpected Hexagon exception MODECTL polling packet at 0x4db8')
        decrement11=(decrement11&~marker)|(1<<14)
        branch11=(branch11&~marker)|(3<<14)
        struct.pack_into('<II',out,rel11,decrement11,branch11)
    return bytes(out)


def assemble(llvm_mc:Path,source:Path)->bytes:
    with tempfile.TemporaryDirectory(prefix="nabu-agent11-hexagon-") as td:
        obj=Path(td)/"source.o"
        cmd=[str(llvm_mc),"-triple=hexagon","-mcpu=hexagonv60","-filetype=obj",str(source),"-o",str(obj)]
        result=subprocess.run(cmd,capture_output=True,text=True,check=False)
        if result.returncode:
            raise ValueError("Hexagon V60 source assembly failed: "+result.stderr.strip())
        encoded=restore_original_legal_hexagon_packet_order(text_from_object(obj.read_bytes()))
    if len(encoded)%4:
        raise ValueError("Hexagon emission does not end on a 32-bit instruction boundary")
    if not encoded:
        raise ValueError("empty assembled Hexagon text is not a verified fragment")
    return encoded


def verify_reference(reference:bytes,generated:bytes,start:int=FILE_START)->None:
    digest=hashlib.sha256(reference).hexdigest()
    if digest!=EXPECTED_SHA256:
        raise ValueError(f"incorrect revision of modem.mbn: {digest}")
    end=start+len(generated)
    expected=reference[start:end]
    if len(expected)!=len(generated):
        raise ValueError(f"truncated reference before file offset {end:#x}")
    if generated!=expected:
        mismatches=[i for i,(a,b) in enumerate(zip(expected,generated)) if a!=b]
        i=mismatches[0]
        raise ValueError(f"modem byte difference at file {start+i:#x}: reference={expected[i]:#04x}, generated={generated[i]:#04x}")


def main()->int:
    parser=argparse.ArgumentParser(description=__doc__)
    root=Path(__file__).resolve().parents[1]
    parser.add_argument("--llvm-mc",required=True,type=Path)
    parser.add_argument("--source",type=Path,default=root/"crates/firmware-tools/src/devices/xiaomi_nabu/modem_entry_followup.s")
    parser.add_argument("--output",required=True,type=Path)
    parser.add_argument("--reference",type=Path,help="private unchanged modem.mbn revision for byte equality")
    args=parser.parse_args()
    try:
        code=assemble(args.llvm_mc,args.source)
        if args.reference:verify_reference(args.reference.read_bytes(),code)
        args.output.write_bytes(code)
        print(f"Emitted {len(code)} source-generated Hexagon bytes, modem file [{FILE_START:#x},{FILE_START+len(code):#x}), physical [{PHYSICAL_START:#x},{PHYSICAL_START+len(code):#x}); SHA256 {hashlib.sha256(code).hexdigest()}")
        if args.reference:print("Reference bytes match exactly (same pinned source revision)")
        print("Partial reconstruction only, not an authenticated or flashable MBN")
        return 0
    except (ValueError,OSError) as exc:
        print("ERROR:",exc,file=sys.stderr)
        return 1

if __name__=="__main__":sys.exit(main())

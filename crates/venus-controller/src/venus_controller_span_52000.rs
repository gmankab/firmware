/// Register-indexed LDRH/STRH with a *negative* displacement. For this
/// A32 form, bit U=0 and I=0. Reject PC as base/operand to avoid unpredictable
/// encodings. This is independent ARM ISA construction, not an opcode copy.
fn halfword_register_negative(cond:C, load:bool, rd:R, base:R, index:R)->Result<u32,String>{
 if [rd,base,index].contains(&R::PC) || base==R::SP && index==R::SP {
   return Err("unsafe register in negative halfword transfer".into());
 }
 Ok(((cond as u32)<<28)|0x0100_00b0|(if load {1<<20}else{0})|
      (base.number()<<16)|(rd.number()<<12)|index.number())
}
struct Code {at:usize,bytes:Vec<u8>}
impl Code {
 fn new()->Self{Self{at:START,bytes:Vec::with_capacity(END-START)}}
 fn check(&self,a:usize)->Result<(),String>{if self.at!=a{return Err(format!("Agent04 A32 {:#x} expected {a:#x}",self.at));}Ok(())}
 #[inline(never)]fn emit(&mut self,w:u32)->Result<(),String>{
   if !(0x40000..0x68000).contains(&self.at)||self.at&3!=0{return Err("Agent04 region boundary".into());}
   self.bytes.extend_from_slice(&w.to_le_bytes());self.at+=4;Ok(())
 }
 fn literal(&mut self,c:C,rd:R,target:usize)->Result<(),String>{
   let d=i32::try_from(target as i64-self.at as i64-8).map_err(|_|"literal offset overflow")?;
   self.emit(arm32::transfer_word(c,true,rd,R::PC,d)?)
 }
}


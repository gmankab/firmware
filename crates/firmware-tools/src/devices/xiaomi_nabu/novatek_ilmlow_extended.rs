/// Constructs exactly the postmarketOS executable bytes in the currently
/// understood region. The map220v revision is intentionally not extrapolated.
pub(super) fn instructions(profile:Profile) -> Vec<Located> {
    if profile==Profile::Map220v {return vec![];}
    let mut out=event_dispatch_and_status();
    out.extend(communication_ring_helpers());
    out.extend(sensor_calibration_and_controls());
    out.extend(report_and_scan_helpers());
    out.extend(extended_coordinate_decoder());
    debug_assert_eq!(out.first().unwrap().pc as usize,FILE_START-0x200);
    debug_assert_eq!(out.last().unwrap().pc as usize,FILE_END-0x200-2);
    out
}

#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn independently_constructed_early_ilm_sequence_is_contiguous(){
        let items=instructions(Profile::Postmarketos);
        assert_eq!(items.len(),1316);
        let mut file=FILE_START;
        for i in items {
            assert_eq!(i.pc as usize,file-0x200);
            file+=i.instruction.encode(i.pc,Profile::Postmarketos.gp()).unwrap().len();
        }
        assert_eq!(file,FILE_END);
    }
}

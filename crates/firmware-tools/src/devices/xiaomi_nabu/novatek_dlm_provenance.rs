//! Exact postmarketOS Nabu Novatek byte-provenance ledger.
//!
//! This ledger records evidence claims; constructing a claim is not proof of
//! independent authorship or reference equality. The caller must verify each
//! claimed DLM span against its semantic generator and pinned reference.
//! Neither parsing a vendor scalar nor finding zero bytes grants source credit.
//! The configuration mirror is always a derived region, even when its upstream
//! DLM bytes have an independent source implementation.

use super::novatek_layout::{
    CANDIDATE_VECTORS_END, DLM_FILE_END, DLM_FILE_START, DLM_MIRROR_BYTES,
    DLM_MIRROR_START, END_MARKER_OFFSET, HEADER_BYTES, ILM_CODE_START,
    ILM_SPACER_START, IMAGE_LENGTH, POST_DLM_PADDING_END, RESERVED_TAIL_START,
};

/// Freeze the previously audited 538-byte ILM contribution. Changes to another
/// agent's ILM coverage must not silently promote additional bytes in this DLM
/// ledger; integration can add separately verified evidence in a later change.
pub const PRIOR_SOURCE_EXECUTABLE_END: usize = 0x66a;

/// A DLM-only, independently structured *data* claim. There is deliberately no
/// executable flag: Agent 19 does not own ILM implementation or code coverage.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct DlmClaim {
    pub file_start: usize,
    pub file_end: usize,
    pub evidence: &'static str,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum LedgerKind {
    SourceLayout,
    SourceExecutable,
    ExternalMetadata,
    SourceDlmData,
    UnknownIlm,
    UnknownDlm,
    DerivedMirror,
}

impl LedgerKind {
    pub fn as_str(self) -> &'static str {
        match self {
            Self::SourceLayout => "source_layout",
            Self::SourceExecutable => "source_executable",
            Self::ExternalMetadata => "external_metadata",
            Self::SourceDlmData => "source_dlm_data",
            Self::UnknownIlm => "unknown_ilm",
            Self::UnknownDlm => "unknown_dlm",
            Self::DerivedMirror => "derived_mirror",
        }
    }
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct MirrorSource {
    pub file_start: usize,
    pub file_end: usize,
    pub independently_authored: bool,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct LedgerRow {
    pub file_start: usize,
    pub file_end: usize,
    pub kind: LedgerKind,
    pub evidence: &'static str,
    pub mirror_source: Option<MirrorSource>,
}

impl LedgerRow {
    pub fn len(self) -> usize {
        self.file_end - self.file_start
    }

    pub fn is_empty(self) -> bool {
        self.file_start == self.file_end
    }
}

#[derive(Debug, Default, Clone, Copy, PartialEq, Eq)]
pub struct LedgerTotals {
    pub source_layout_bytes: usize,
    pub source_executable_bytes: usize,
    pub external_metadata_bytes: usize,
    pub source_dlm_data_bytes: usize,
    pub unknown_ilm_bytes: usize,
    pub unknown_dlm_bytes: usize,
    /// Physical mirror bytes; counted exactly once in `total_bytes()`.
    pub derived_mirror_bytes: usize,
    /// Subset of `derived_mirror_bytes`, not additional independent coverage.
    pub mirror_from_source_bytes: usize,
    /// Subset of `derived_mirror_bytes` still depending on unknown DLM bytes.
    pub mirror_from_external_bytes: usize,
}

impl LedgerTotals {
    /// Sum only mutually exclusive physical-image categories.
    pub fn total_bytes(self) -> usize {
        self.source_layout_bytes
            + self.source_executable_bytes
            + self.external_metadata_bytes
            + self.source_dlm_data_bytes
            + self.unknown_ilm_bytes
            + self.unknown_dlm_bytes
            + self.derived_mirror_bytes
    }

    /// Unique independently generated bytes; excludes duplicated mirror data
    /// and metadata whose values remain supplied by the pinned reference.
    pub fn independent_bytes(self) -> usize {
        self.source_layout_bytes + self.source_executable_bytes + self.source_dlm_data_bytes
    }

    pub fn unknown_payload_bytes(self) -> usize {
        self.unknown_ilm_bytes + self.unknown_dlm_bytes
    }
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ProvenanceLedger {
    pub rows: Vec<LedgerRow>,
    pub totals: LedgerTotals,
    pub first_unknown_dlm: Option<usize>,
}

fn row(start: usize, end: usize, kind: LedgerKind, evidence: &'static str) -> LedgerRow {
    LedgerRow {
        file_start: start,
        file_end: end,
        kind,
        evidence,
        mirror_source: None,
    }
}

/// Classify the exact 196,608-byte pinned image from explicit DLM data claims.
/// Claims may arrive in any order; overlaps, empty ranges, missing evidence,
/// and ranges outside the Agent 19 DLM reservation are rejected. The function
/// never reads reference payload bytes, so incidental zero runs or external
/// round-trips cannot automatically acquire independent-source credit.
pub fn build_ledger(claims: &[DlmClaim]) -> Result<ProvenanceLedger, String> {
    let mut ordered = claims.to_vec();
    ordered.sort_by_key(|claim| (claim.file_start, claim.file_end));
    let mut dlm_rows = Vec::new();
    let mut cursor = DLM_FILE_START;
    for claim in ordered {
        if claim.file_start < DLM_FILE_START || claim.file_end > DLM_FILE_END {
            return Err(format!(
                "DLM claim 0x{:x}..0x{:x} outside owned range 0x{DLM_FILE_START:x}..0x{DLM_FILE_END:x}",
                claim.file_start, claim.file_end
            ));
        }
        if claim.file_end <= claim.file_start {
            return Err(format!("empty or reversed DLM claim at 0x{:x}", claim.file_start));
        }
        if claim.evidence.trim().is_empty() {
            return Err(format!("missing semantic evidence for DLM claim at 0x{:x}", claim.file_start));
        }
        if claim.file_start < cursor {
            return Err(format!("overlapping DLM claim at 0x{:x}", claim.file_start));
        }
        if cursor < claim.file_start {
            dlm_rows.push(row(cursor, claim.file_start, LedgerKind::UnknownDlm,
                "DLM payload not independently reconstructed"));
        }
        dlm_rows.push(row(claim.file_start, claim.file_end, LedgerKind::SourceDlmData,
            claim.evidence));
        cursor = claim.file_end;
    }
    if cursor < DLM_FILE_END {
        dlm_rows.push(row(cursor, DLM_FILE_END, LedgerKind::UnknownDlm,
            "DLM payload not independently reconstructed"));
    }
    let first_unknown_dlm = dlm_rows.iter()
        .find(|region| region.kind == LedgerKind::UnknownDlm)
        .map(|region| region.file_start);

    let mut rows = vec![
        row(0, HEADER_BYTES, LedgerKind::ExternalMetadata,
            "dual-bank metadata scalars; CRCs recomputable from payload"),
        row(HEADER_BYTES, CANDIDATE_VECTORS_END, LedgerKind::ExternalMetadata,
            "candidate vector words with externally supplied target scalars"),
        row(CANDIDATE_VECTORS_END, ILM_CODE_START, LedgerKind::SourceLayout,
            "verified vector-to-code zero padding"),
        row(ILM_CODE_START, PRIOR_SOURCE_EXECUTABLE_END, LedgerKind::SourceExecutable,
            "prior Agent 09 typed NDS32 boot/reset prefix"),
        row(PRIOR_SOURCE_EXECUTABLE_END, ILM_SPACER_START, LedgerKind::UnknownIlm,
            "ILM remainder owned by Agents 17 and 18"),
        row(ILM_SPACER_START, DLM_FILE_START, LedgerKind::SourceLayout,
            "verified ILM-to-DLM zero padding"),
    ];
    rows.extend(dlm_rows.iter().copied());
    rows.push(row(DLM_FILE_END, POST_DLM_PADDING_END, LedgerKind::SourceLayout,
        "verified post-DLM zero padding"));

    // Alias the same first 2,304 DLM bytes without crediting them twice.
    let mirrored_dlm_end = DLM_FILE_START + DLM_MIRROR_BYTES;
    for source in &dlm_rows {
        let start = source.file_start.max(DLM_FILE_START);
        let end = source.file_end.min(mirrored_dlm_end);
        if start >= end { continue; }
        rows.push(LedgerRow {
            file_start: DLM_MIRROR_START + start - DLM_FILE_START,
            file_end: DLM_MIRROR_START + end - DLM_FILE_START,
            kind: LedgerKind::DerivedMirror,
            evidence: source.evidence,
            mirror_source: Some(MirrorSource {
                file_start: start,
                file_end: end,
                independently_authored: source.kind == LedgerKind::SourceDlmData,
            }),
        });
    }
    rows.push(row(RESERVED_TAIL_START, END_MARKER_OFFSET, LedgerKind::SourceLayout,
        "verified reserved tail zero padding"));
    rows.push(row(END_MARKER_OFFSET, IMAGE_LENGTH, LedgerKind::SourceLayout,
        "constant NVT image terminator"));

    let totals = validate_and_total(&rows)?;
    Ok(ProvenanceLedger { rows, totals, first_unknown_dlm })
}

fn validate_and_total(rows: &[LedgerRow]) -> Result<LedgerTotals, String> {
    let mut totals = LedgerTotals::default();
    let mut cursor = 0;
    for region in rows {
        if region.file_start != cursor || region.file_end <= region.file_start
            || region.file_end > IMAGE_LENGTH {
            return Err(format!("nonpartitioning provenance row at 0x{:x}", region.file_start));
        }
        let bytes = region.len();
        match region.kind {
            LedgerKind::SourceLayout => totals.source_layout_bytes += bytes,
            LedgerKind::SourceExecutable => totals.source_executable_bytes += bytes,
            LedgerKind::ExternalMetadata => totals.external_metadata_bytes += bytes,
            LedgerKind::SourceDlmData => totals.source_dlm_data_bytes += bytes,
            LedgerKind::UnknownIlm => totals.unknown_ilm_bytes += bytes,
            LedgerKind::UnknownDlm => totals.unknown_dlm_bytes += bytes,
            LedgerKind::DerivedMirror => {
                let source = region.mirror_source.ok_or("missing mirror source provenance")?;
                if source.file_start < DLM_FILE_START
                    || source.file_end > DLM_FILE_START + DLM_MIRROR_BYTES
                    || source.file_end <= source.file_start
                    || source.file_end - source.file_start != bytes
                    || region.file_start != DLM_MIRROR_START + source.file_start - DLM_FILE_START {
                    return Err("invalid DLM mirror provenance mapping".into());
                }
                totals.derived_mirror_bytes += bytes;
                if source.independently_authored {
                    totals.mirror_from_source_bytes += bytes;
                } else {
                    totals.mirror_from_external_bytes += bytes;
                }
            }
        }
        if region.kind != LedgerKind::DerivedMirror && region.mirror_source.is_some() {
            return Err("nonmirror row has mirror provenance".into());
        }
        cursor = region.file_end;
    }
    if cursor != IMAGE_LENGTH || totals.total_bytes() != IMAGE_LENGTH
        || totals.derived_mirror_bytes != DLM_MIRROR_BYTES
        || totals.mirror_from_source_bytes + totals.mirror_from_external_bytes != DLM_MIRROR_BYTES {
        return Err("provenance totals do not cover the complete pinned image".into());
    }
    Ok(totals)
}

#[cfg(test)]
mod tests {
    use super::*;

    fn claim(start: usize, end: usize) -> DlmClaim {
        DlmClaim { file_start: start, file_end: end, evidence: "test semantic data rule" }
    }

    #[test]
    fn baseline_counts_keep_all_provenance_categories_separate() {
        let ledger = build_ledger(&[]).unwrap();
        assert_eq!(ledger.totals, LedgerTotals {
            source_layout_bytes: 35_136,
            source_executable_bytes: 538,
            external_metadata_bytes: 1_024,
            source_dlm_data_bytes: 0,
            unknown_ilm_bytes: 108_054,
            unknown_dlm_bytes: 49_552,
            derived_mirror_bytes: 2_304,
            mirror_from_source_bytes: 0,
            mirror_from_external_bytes: 2_304,
        });
        assert_eq!(ledger.totals.total_bytes(), 196_608);
        assert_eq!(ledger.totals.independent_bytes(), 35_674);
        assert_eq!(ledger.totals.unknown_payload_bytes(), 157_606);
        assert_eq!(ledger.first_unknown_dlm, Some(0x22000));
    }

    #[test]
    fn sparse_claims_make_a_sorted_complete_disjoint_partition() {
        let claims = [claim(0x24000, 0x24100), claim(0x22010, 0x22030)];
        let ledger = build_ledger(&claims).unwrap();
        assert_eq!(ledger.rows.first().unwrap().file_start, 0);
        assert_eq!(ledger.rows.last().unwrap().file_end, IMAGE_LENGTH);
        for pair in ledger.rows.windows(2) {
            assert_eq!(pair[0].file_end, pair[1].file_start);
        }
        assert_eq!(ledger.totals.source_dlm_data_bytes, 288);
        assert_eq!(ledger.totals.unknown_dlm_bytes, 49_552 - 288);
        assert_eq!(ledger.totals.total_bytes(), IMAGE_LENGTH);
        assert_eq!(ledger.first_unknown_dlm, Some(DLM_FILE_START));
    }

    #[test]
    fn mirror_provenance_follows_only_intersecting_upstream_claims() {
        let ledger = build_ledger(&[
            claim(0x22000, 0x22020),
            claim(0x228f0, 0x22920), // only 16 bytes fall within mirrored prefix
            claim(0x23000, 0x23100), // no mirror contribution
        ]).unwrap();
        assert_eq!(ledger.first_unknown_dlm, Some(0x22020));
        assert_eq!(ledger.totals.mirror_from_source_bytes, 48);
        assert_eq!(ledger.totals.mirror_from_external_bytes, 2304 - 48);
        assert_eq!(ledger.totals.derived_mirror_bytes, 2304);
        let mirrored: Vec<_> = ledger.rows.iter()
            .filter(|r| r.kind == LedgerKind::DerivedMirror).collect();
        assert_eq!(mirrored.len(), 3);
        assert_eq!((mirrored[0].file_start, mirrored[0].file_end), (0x2f000, 0x2f020));
        assert!(mirrored[0].mirror_source.unwrap().independently_authored);
        assert!(!mirrored[1].mirror_source.unwrap().independently_authored);
        assert_eq!((mirrored[2].file_start, mirrored[2].file_end), (0x2f8f0, 0x2f900));
        assert_eq!(ledger.totals.independent_bytes(), 35_674 + 32 + 48 + 256);
    }

    #[test]
    fn adjacent_claims_are_valid_and_first_hole_is_exact() {
        let ledger = build_ledger(&[claim(0x22020, 0x22040), claim(0x22000, 0x22020)]).unwrap();
        assert_eq!(ledger.first_unknown_dlm, Some(0x22040));
        assert_eq!(ledger.totals.source_dlm_data_bytes, 64);
        assert_eq!(ledger.totals.mirror_from_source_bytes, 64);
    }

    #[test]
    fn rejects_overlapping_duplicate_and_nested_claims() {
        for claims in [
            [claim(0x22000, 0x22020), claim(0x22010, 0x22030)],
            [claim(0x22000, 0x22020), claim(0x22000, 0x22020)],
            [claim(0x22000, 0x22100), claim(0x22010, 0x22020)],
        ] {
            assert!(build_ledger(&claims).unwrap_err().contains("overlapping"));
        }
    }

    #[test]
    fn rejects_out_of_scope_empty_reversed_and_unexplained_claims() {
        for invalid in [
            claim(0x10000, 0x10010),
            claim(0x21fff, 0x22001),
            claim(0x2e18f, 0x2e191),
            claim(0x2f000, 0x2f010),
            claim(0x22000, 0x22000),
            claim(0x22010, 0x22000),
            claim(usize::MAX, usize::MAX),
            DlmClaim { file_start: 0x22000, file_end: 0x22001, evidence: " \n " },
        ] {
            assert!(build_ledger(&[invalid]).is_err());
        }
    }

    #[test]
    fn full_dlm_claim_never_promotes_executable_or_metadata_counts() {
        // Even an unproven caller claim for every DLM byte cannot masquerade
        // as ILM reconstruction; proof and byte checking remain caller duties.
        let ledger = build_ledger(&[claim(DLM_FILE_START, DLM_FILE_END)]).unwrap();
        assert_eq!(ledger.totals.source_dlm_data_bytes, 49_552);
        assert_eq!(ledger.totals.source_executable_bytes, 538);
        assert_eq!(ledger.totals.external_metadata_bytes, 1024);
        assert_eq!(ledger.totals.source_layout_bytes, 35_136);
        assert_eq!(ledger.totals.unknown_ilm_bytes, 108_054);
        assert_eq!(ledger.totals.unknown_dlm_bytes, 0);
        assert_eq!(ledger.totals.mirror_from_source_bytes, 2304);
        assert_eq!(ledger.totals.total_bytes(), IMAGE_LENGTH);
        assert_eq!(ledger.first_unknown_dlm, None);
    }
}

#[cfg(test)] mod tests{
    use super::*;
    #[test] fn extension5_has_exact_checked_instruction_coverage(){
        let insns=instructions(Profile::Postmarketos);
        assert_eq!(insns.len(), 862);
        assert!(instructions(Profile::Map220v).is_empty());
        let mut pc=FILE_START-0x200;
        for i in &insns{
            assert_eq!(i.pc,pc as u32,"gap/overlap in extension5");
            let enc=i.instruction.encode(i.pc,Profile::Postmarketos.gp()).unwrap();
            assert!(enc.len()==2 || enc.len()==4,"unexpected NDS32 instruction width");
            pc+=enc.len();
        }
        assert_eq!(pc+0x200,FILE_END);
    }
}

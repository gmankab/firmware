use arm32::{Condition as C,DataOp as Op,Register as R,Shift};
pub const START:usize=0x4e000;
pub const END:usize=0x4f000;
const WIDTH_MASK:u32=0xffc03f0f;
const SIGN_MASK:u32=0x7fff8000;
const FLOAT_COEFFICIENT:u32=0x0548eba0;
struct Code {at:usize,bytes:Vec<u8>}
impl Code {
 fn new()->Self {Self{at:START,bytes:Vec::with_capacity(END-START)}}
 fn check(&self,a:usize)->Result<(),String>{
  if self.at!=a {return Err(format!("Agent04 A32 at {:#x} expected {a:#x}",self.at));}Ok(())
 }
 #[inline(never)]
 fn emit(&mut self,w:u32)->Result<(),String>{
  if !(0x40000..0x68000).contains(&self.at)||self.at&3!=0{return Err("Agent04 region boundary".into());}
  self.bytes.extend_from_slice(&w.to_le_bytes());self.at+=4;Ok(())
 }
 fn literal(&mut self,c:C,rd:R,target:usize)->Result<(),String>{
  let displacement=i32::try_from(target as i64-self.at as i64-8).map_err(|_|"literal displacement overflow")?;
  self.emit(arm32::transfer_word(c,true,rd,R::PC,displacement)?)
 }
}


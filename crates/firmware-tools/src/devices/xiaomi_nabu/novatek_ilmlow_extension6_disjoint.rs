/// Build one disjoint interval without filling source gaps.
pub fn emit(fragment:&Fragment)->Result<Vec<u8>,String>{
    let mut output=Vec::new();
    for item in &fragment.code {
        let expected=fragment.file_start-0x200+output.len();
        if item.pc as usize!=expected{return Err(format!("noncontiguous disjoint subregion at {expected:#x}"));}
        output.extend(item.instruction.encode(item.pc,Profile::Postmarketos.gp())?);
    }
    if fragment.file_start+output.len()!=fragment.file_end{return Err("disjoint source byte count mismatch".into());}
    Ok(output)
}

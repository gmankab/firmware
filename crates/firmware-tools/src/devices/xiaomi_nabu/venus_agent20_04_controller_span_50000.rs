struct Code{at:usize,bytes:Vec<u8>}
impl Code {
 fn new()->Self{Self{at:START,bytes:Vec::with_capacity(END-START)}}
 fn check(&self,a:usize)->Result<(),String>{
  if self.at!=a{return Err(format!("Venus controller 0x{:x} expected 0x{a:x}",self.at));}Ok(())
 }
 #[inline(never)]fn emit(&mut self,w:u32)->Result<(),String>{
  if !(0x40000..0x68000).contains(&self.at)||self.at&3!=0{return Err("outside Agent04 range".into());}
  self.bytes.extend_from_slice(&w.to_le_bytes());self.at+=4;Ok(())
 }
 fn literal(&mut self,c:C,rd:R,dest:usize)->Result<(),String>{
  let off=i32::try_from(dest as i64-self.at as i64-8).map_err(|_|"literal displacement too large")?;
  self.emit(arm32::transfer_word(c,true,rd,R::PC,off)?)
 }
}


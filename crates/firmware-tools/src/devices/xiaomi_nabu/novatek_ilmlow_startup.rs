//! Complete startup controller routine after the descriptor diagnostic path.
//! PostmarketOS runtime [0x75a,0x91a); map220v [0x75a,0x91c).
//! The older profile uses a four-byte SWI.GP where the postmarketOS profile
//! uses a two-byte EX9 entry. All following PCs and local targets are shifted
//! explicitly; numeric MMIO addresses are not assigned undocumented names.

use super::{Located, Profile};
use super::isa::{Csr, Insn, Reg, Width};

fn r(n: u8) -> Reg { Reg::new(n) }

struct Links {
    setup_call: u32,
    after_reset_call: u32,
    conditional_call: u32,
    mode_call: u32,
    result_call: u32,
    repeated_call: u32,
    final_call: u32,
    cleared_byte: u32,
    descriptor_base: u32,
    descriptor_pointer: u32,
    second_clear: u32,
    result_slot: u32,
    ex_mmio_r0: u16,
    ex_reset_area_r1: u16,
    ex_status_r0: u16,
    ex_word_clear: u16,
    ex_status0_r0: u16,
    ex_memory_r0: u16,
    ex_or8_r0: u16,
    ex_start_call: u16,
    ex_byte_store: u16,
}


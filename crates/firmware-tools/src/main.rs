/// Compare sparse typed framing without reading full firmware payloads.
fn verify_sparse(file: &std::path::Path, expected_len: u64,
    spans: impl IntoIterator<Item=(usize,Vec<u8>)>) -> Result<usize,Box<dyn Error>> {
    let mut reference=fs::File::open(file)?;
    if reference.metadata()?.len()!=expected_len {
        return Err(format!("wrong full image length for {}",file.display()).into());
    }
    let mut end=0;
    let mut total=0;
    for (offset,data) in spans {
        let start=offset as u64;
        let next=start.checked_add(data.len() as u64).ok_or("metadata span overflow")?;
        if start<end || next>expected_len || data.is_empty() {
            return Err(format!("invalid framing span at 0x{offset:x}").into());
        }
        reference.seek(SeekFrom::Start(start))?;
        let mut current=vec![0u8;data.len()];
        reference.read_exact(&mut current)?;
        if current!=data {
            return Err(format!("framing differs at file offset 0x{offset:x}").into());
        }
        total+=data.len();
        end=next;
    }
    Ok(total)
}

fn venus_reference_identity() -> Result<(usize, &'static str), Box<dyn Error>> {
    let identity = firmware_tools::firmware_manifest_identity::canonical_image("venus.mbn")?;
    Ok((identity.size, identity.sha256))
}

fn verify_venus_upper_dispatch(reference: &[u8], bytes: &[u8]) -> Result<(), Box<dyn Error>> {
    use firmware_tools::devices::xiaomi_nabu::venus_upper_dispatch as dispatch;
    let (size, sha256) = venus_reference_identity()?;
    if reference.len() != size {
        return Err("wrong full Venus reference length".into());
    }
    if firmware_tools::wmfw_sha256::hex_digest(reference) != sha256 {
        return Err("Venus reference SHA-256 differs from canonical record".into());
    }
    let offset = dispatch::START + dispatch::FILE_MAPPING_DELTA;
    let end = offset.checked_add(bytes.len()).ok_or("Venus dispatch offset overflow")?;
    if reference.get(offset..end) != Some(bytes) {
        return Err("Venus upper dispatch differs from pinned reference".into());
    }
    Ok(())
}


//! CDSP typed Hexagon V66 callback-poll routine and contiguous RWE verifier.
use firmware_tools::devices::xiaomi_nabu::cdsp_late_callback_poll as poll;
use std::{env,error::Error,fs};
fn main()->Result<(),Box<dyn Error>>{
    let a:Vec<_>=env::args().skip(1).collect();
    if a.len()!=2 {return Err("usage: cdsp-late-callback-poll <emit|verify|emit-prefix|verify-prefix> FILE".into());}
    match a[0].as_str(){
        "emit"=>{
            let code=poll::build_polled_callback_loop()?;
            fs::write(&a[1],&code)?;
            println!("Generated {} typed Hexagon executable bytes",code.len());
        },
        "verify"=>{
            poll::verify_polled_callback_loop(&fs::read(&a[1])?)?;
            println!("Verified {} source-generated bytes at CDSP 0x{:x}",poll::EXECUTABLE_LEN,poll::FILE_OFFSET);
        },
        "emit-prefix"=>{
            let prefix=poll::build_rwe_prefix_through_poll()?;
            fs::write(&a[1],&prefix)?;
            println!("Generated {} RWE bytes: {} source code and 24 layout NOPs",prefix.len(),poll::RWE_EXECUTABLE_LEN);
        },
        "verify-prefix"=>{
            poll::verify_rwe_prefix_through_poll(&fs::read(&a[1])?)?;
            println!("Verified RWE prefix length {} at 0x{:x}",poll::RWE_LAYOUT_LEN,poll::RWE_LAYOUT_START);
        },
        _=>return Err("unknown operation".into()),
    }
    Ok(())
}
